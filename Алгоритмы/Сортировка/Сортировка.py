# БЛОК 7. СОРТИРОВКА ПО НЕСКОЛЬКИМ УСЛОВИЯМ
# ============================================================

students = [
    ['Вера', 84],
    ['Антон', 91],
    ['Борис', 84],
    ['Галина', 91]
]

def sort_key(student):
    score = student[1]
    name = student[0]
    return -score, name

students.sort(key=sort_key)

print(students)

# Короткий вариант:
# students.sort(key=lambda student: (-student[1], student[0]))


