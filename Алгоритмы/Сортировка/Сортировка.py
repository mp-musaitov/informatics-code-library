# БЛОК 10. РУЧНАЯ СОРТИРОВКА ПУЗЫРЬКОМ
# ============================================================

# В обычных задачах используйте sorted() или .sort().
# Этот пример показывает сам принцип работы сортировки.

numbers = [8, 3, 12, 5, 17, 2]

n = len(numbers)

for i in range(n - 1):
    for j in range(n - 1 - i):
        if numbers[j] > numbers[j + 1]:
            numbers[j], numbers[j + 1] = numbers[j + 1], numbers[j]

print(numbers)
