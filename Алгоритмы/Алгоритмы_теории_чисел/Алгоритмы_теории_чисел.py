# БЛОК 3. ДЕЛИТЕЛИ ДО КВАДРАТНОГО КОРНЯ
# ============================================================

n = 36
divisors = []

d = 1

while d * d <= n:
    if n % d == 0:
        divisors.append(d)

        second = n // d

        if second != d:
            divisors.append(second)

    d += 1

divisors.sort()
print(divisors)


