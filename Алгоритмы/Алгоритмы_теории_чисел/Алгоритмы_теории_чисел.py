# БЛОК 4. КОЛИЧЕСТВО И СУММА ДЕЛИТЕЛЕЙ
# ============================================================

n = 36
count = 0
total = 0

d = 1

while d * d <= n:
    if n % d == 0:
        second = n // d

        if d == second:
            count += 1
            total += d
        else:
            count += 2
            total += d + second

    d += 1

print(count)
print(total)


