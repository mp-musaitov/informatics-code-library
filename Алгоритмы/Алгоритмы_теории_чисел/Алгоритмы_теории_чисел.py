limit = 50

prime = [True] * (limit + 1)
prime[0] = False
prime[1] = False

for p in range(2, int(limit ** 0.5) + 1):
    if prime[p]:
        for multiple in range(p * p, limit + 1, p):
            prime[multiple] = False

primes = []

for number in range(2, limit + 1):
    if prime[number]:
        primes.append(number)

print(primes)
