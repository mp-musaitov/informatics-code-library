# БЛОК 5. ПРОВЕРКА ЧИСЛА НА ПРОСТОТУ
# ============================================================

def is_prime(n):
    if n < 2:
        return False

    d = 2

    while d * d <= n:
        if n % d == 0:
            return False

        d += 1

    return True


print(is_prime(37))
print(is_prime(42))


