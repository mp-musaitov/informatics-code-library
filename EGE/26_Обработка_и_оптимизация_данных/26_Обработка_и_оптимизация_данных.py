# БЛОК 1. СУММА ПО КАЖДОМУ ID
# ============================================================
clients = {}

# Пример:
data = [
    (101, 20000),
    (202, 110000),
    (101, 90000),
]

for client, size in data:
    clients[client] = clients.get(client, 0) + size

best_client = max(clients, key=clients.get)

print(best_client)


