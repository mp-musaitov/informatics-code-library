# БЛОК 3. ДЕМОВЕРСИЯ-2027 — ОДИН ПРОХОД ПО ФАЙЛУ
# ============================================================
with open('26.txt') as f:
    n, K = map(int, f.readline().split())

    clients = {}

    used = 0
    max1 = 0
    max2 = 0

    for _ in range(n):
        time, client, size = f.readline().split()

        client = int(client)
        size = int(size)

        # Суммарный объём данных клиента.
        clients[client] = clients.get(client, 0) + size

        # Если новый запрос уже не помещается,
        # сначала создаётся копия старого блока.
        if used + size > K:

            # Копия создаётся во время запроса,
            # который вызвал очистку памяти.
            if time <= '11:59:59':
                if used > max1:
                    max2 = max1
                    max1 = used
                elif used > max2:
                    max2 = used

            # Память очищена.
            # Новый запрос становится первым в новом блоке.
            used = size

        else:
            used += size

best_client = max(clients, key=clients.get)

print(best_client, max1 + max2)


