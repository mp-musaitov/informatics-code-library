# БЛОК 6. ЖАДНЫЙ ВЫБОР ПОСЛЕ СОРТИРОВКИ
# ============================================================
# Типовая задача:
# взять максимальное количество объектов,
# не превысив ограничение limit.

a = [40, 10, 30, 20]
limit = 70

a.sort()

total = 0
count = 0

for x in a:
    if total + x <= limit:
        total += x
        count += 1
    else:
        break

print(count, total)


