# БЛОК 5. ПЕРЕВОД ВРЕМЕНИ В СЕКУНДЫ
# ============================================================
def seconds(t):
    h, m, s = map(int, t.split(':'))
    return h * 3600 + m * 60 + s


print(seconds('11:59:59'))


