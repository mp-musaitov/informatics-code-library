# БЛОК 2. ДВА НАИБОЛЬШИХ ЗНАЧЕНИЯ БЕЗ СПИСКА
# ============================================================
max1 = 0
max2 = 0

values = [100, 80, 70, 100]

for x in values:
    if x > max1:
        max2 = max1
        max1 = x
    elif x > max2:
        max2 = x

print(max1, max2)
print(max1 + max2)


