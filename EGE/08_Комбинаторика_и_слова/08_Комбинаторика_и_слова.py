from itertools import product, permutations


# ============================================================
# БЛОК 1. УНИВЕРСАЛЬНЫЙ ПЕРЕБОР СЛОВ ЧЕРЕЗ PRODUCT
# ============================================================
# Условие:
# Составляются слова фиксированной длины из заданного алфавита.
# Повторы символов разрешены.

alphabet = 'АБВГ'
count = 0

for word in product(alphabet, repeat=5):
    word = ''.join(word)

    if True:  # здесь записываем условие задачи
        count += 1

print(count)


# ============================================================
# БЛОК 2. РОВНО / НЕ БОЛЕЕ / НЕ МЕНЕЕ ОПРЕДЕЛЁННОЙ БУКВЫ
# ============================================================
# Условие:
# Посчитать слова, в которых буква А встречается ровно 2 раза,
# а буква Б — не более 1 раза.

count = 0

for word in product('АБВГ', repeat=5):
    word = ''.join(word)

    if word.count('А') == 2 and word.count('Б') <= 1:
        count += 1

print(count)


# ============================================================
# БЛОК 3. ЗАПРЕЩЁННЫЕ СОЧЕТАНИЯ
# ============================================================
# Условие:
# В слове не должно быть подстрок АА, ББ и АБ.

count = 0

for word in product('АБВГ', repeat=5):
    word = ''.join(word)

    if 'АА' not in word and 'ББ' not in word and 'АБ' not in word:
        count += 1

print(count)


# ============================================================
# БЛОК 4. УСЛОВИЯ НА ПЕРВЫЙ И ПОСЛЕДНИЙ СИМВОЛ
# ============================================================
# Условие:
# Слово начинается с одной из букв Б, В, Г
# и заканчивается буквой А.

count = 0

for word in product('АБВГ', repeat=6):
    word = ''.join(word)

    if word[0] in 'БВГ' and word[-1] == 'А':
        count += 1

print(count)


# ============================================================
# БЛОК 5. ВСЕ СИМВОЛЫ РАЗЛИЧНЫ — PERMUTATIONS
# ============================================================
# Условие:
# Составить слова длины 4 из букв АБВГД без повторений.

count = 0

for word in permutations('АБВГД', 4):
    word = ''.join(word)

    if True:  # дополнительные условия при необходимости
        count += 1

print(count)


# ============================================================
# БЛОК 6. ПРОВЕРКА ОТСУТСТВИЯ ПОВТОРОВ ЧЕРЕЗ SET
# ============================================================
# Условие:
# Повторы запрещены, но есть и другие условия,
# поэтому удобно оставить product и проверить уникальность отдельно.

count = 0

for word in product('АБВГДЕ', repeat=5):
    word = ''.join(word)

    if len(word) == len(set(word)) and word[0] != 'А':
        count += 1

print(count)


# ============================================================
# БЛОК 7. ПЕРЕСТАНОВКИ БУКВ ЗАДАННОГО СЛОВА
# ============================================================
# Условие:
# Нужно получить все различные перестановки букв слова,
# в котором могут быть одинаковые символы.

words = set(permutations('МАМА'))
print(len(words))


# ============================================================
# БЛОК 8. ЧИСЛА В СИСТЕМЕ СЧИСЛЕНИЯ
# ============================================================
# Условие:
# Перебираются пятизначные семеричные числа.
# Первая цифра не может быть нулём.

count = 0

for digits in product('0123456', repeat=5):
    number = ''.join(digits)

    if number[0] == '0':
        continue

    if True:  # здесь записываем условие задачи
        count += 1

print(count)


# ============================================================
# БЛОК 9. ЛЕКСИКОГРАФИЧЕСКИЙ ПОРЯДОК — ПОИСК НОМЕРА СЛОВА
# ============================================================
# Условие:
# Все слова одинаковой длины записаны в порядке,
# заданном алфавитом. Нужно найти номер конкретного слова.
# ВАЖНО: alphabet должен быть записан именно в порядке из условия.

alphabet = 'АБВГ'

for i, word in enumerate(product(alphabet, repeat=3), 1):
    word = ''.join(word)

    if word == 'ВБА':
        print(i)
        break


