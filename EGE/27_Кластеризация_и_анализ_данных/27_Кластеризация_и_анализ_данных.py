# ЕГЭ №27. Кластеризация и анализ данных

from math import dist


# ============================================================
# БЛОК 1. ЧТЕНИЕ ДАННЫХ И РАСЧЁТ ЭНЕРГИИ
# ============================================================
particles = []

with open('27.txt') as f:
    for s in f:
        x, y, vx, vy, m, mark = s.replace(',', '.').split()

        x = float(x)
        y = float(y)
        vx = float(vx)
        vy = float(vy)
        m = float(m)

        E = m * (vx ** 2 + vy ** 2) / 2

        particles.append([x, y, mark, E])


# ============================================================
# БЛОК 2. РАЗБИЕНИЕ НА КЛАСТЕРЫ ПО ЭНЕРГИИ
# ============================================================
R = 2

particles.sort(key=lambda p: p[3])

clusters = []

for p in particles:
    if not clusters:
        clusters.append([p])

    elif p[3] - clusters[-1][0][3] <= R:
        clusters[-1].append(p)

    else:
        clusters.append([p])

print(len(clusters))
print([len(cl) for cl in clusters])


# ============================================================
# БЛОК 3. ЦЕНТР КЛАСТЕРА ПО ЭНЕРГИИ
# ============================================================
# Центр — одна из частиц кластера, для которой
# сумма модулей разностей энергий минимальна.

def center(cl):
    best = None
    best_sum = None

    for p in cl:
        s = sum(abs(p[3] - q[3]) for q in cl)

        if best_sum is None or s < best_sum:
            best_sum = s
            best = p

    return best


centers = [center(cl) for cl in clusters]


# ============================================================
# БЛОК 4. Q1 — МАКСИМАЛЬНОЕ РАССТОЯНИЕ МЕЖДУ ЧАСТИЦАМИ II
# ============================================================
Q1 = None

for cl in clusters:
    a = [p for p in cl if p[2] == 'II']

    for i in range(len(a)):
        for j in range(i + 1, len(a)):
            d = dist(a[i][:2], a[j][:2])

            if Q1 is None or d > Q1:
                Q1 = d


# ============================================================
# БЛОК 5. Q2 — МАКСИМАЛЬНАЯ ЭНЕРГИЯ ЦЕНТРА
# ============================================================
Q2 = max(p[3] for p in centers)


# ============================================================
# БЛОК 6. ОТВЕТ ДЕМОВЕРСИИ-2027
# ============================================================
print(int(Q1 * 10000), int(Q2 * 10000))


# ============================================================
# БЛОК 7. ЦЕНТР КЛАСТЕРА НА ПЛОСКОСТИ
# ============================================================
# Для классических вариантов, где центр определяется
# как исходная точка с минимальной суммой расстояний
# до остальных точек кластера.

def center_xy(cl):
    best = None
    best_sum = None

    for p in cl:
        s = sum(dist(p, q) for q in cl)

        if best_sum is None or s < best_sum:
            best_sum = s
            best = p

    return best


# ============================================================
# БЛОК 8. МАКСИМАЛЬНОЕ РАССТОЯНИЕ ВНУТРИ КЛАСТЕРА
# ============================================================
# Заготовка для точек вида [x, y].

def max_distance(cl):
    best = 0

    for i in range(len(cl)):
        for j in range(i + 1, len(cl)):
            best = max(best, dist(cl[i], cl[j]))

    return best


# ============================================================
# БЛОК 9. МИНИМАЛЬНОЕ РАССТОЯНИЕ МЕЖДУ ДВУМЯ КЛАСТЕРАМИ
# ============================================================
# Заготовка для точек вида [x, y].

def min_distance_between(cl1, cl2):
    best = float('inf')

    for p in cl1:
        for q in cl2:
            best = min(best, dist(p, q))

    return best


