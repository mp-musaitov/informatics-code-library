# БЛОК 9. ПРОВЕРКА НА ПРОСТОЕ ЧИСЛО
# ============================================================
def is_prime(n):
    if n < 2:
        return False

    for d in range(2, int(n ** 0.5) + 1):
        if n % d == 0:
            return False

    return True


# ============================================================
# БЛОК 10. ПРОСТЫЕ ДЕЛИТЕЛИ
# ============================================================
def prime_divisors(n):
    result = []

    for d in range(2, int(n ** 0.5) + 1):
        if n % d == 0:
            if is_prime(d):
                result.append(d)

            second = n // d

            if second != d and is_prime(second):
                result.append(second)

    return sorted(result)


