# БЛОК 5. МИНИМАЛЬНЫЙ НЕТРИВИАЛЬНЫЙ ДЕЛИТЕЛЬ
# ============================================================
def min_divisor(n):
    for d in range(2, int(n ** 0.5) + 1):
        if n % d == 0:
            return d

    return None


# ============================================================
# БЛОК 6. МИНИМАЛЬНЫЙ И МАКСИМАЛЬНЫЙ ДЕЛИТЕЛИ
# ============================================================
def min_max_divisors(n):
    for d in range(2, int(n ** 0.5) + 1):
        if n % d == 0:
            return d, n // d

    return None


# ============================================================
# БЛОК 7. РАЗНОСТЬ КРАЙНИХ НЕТРИВИАЛЬНЫХ ДЕЛИТЕЛЕЙ
# ============================================================
def k_value(n):
    for d in range(2, int(n ** 0.5) + 1):
        if n % d == 0:
            return n // d - d

    return 0


# ============================================================
# БЛОК 8. КОЛИЧЕСТВО ДЕЛИТЕЛЕЙ
# ============================================================
def count_divisors(n):
    count = 0

    for d in range(1, int(n ** 0.5) + 1):
        if n % d == 0:
            count += 2

    if int(n ** 0.5) ** 2 == n:
        count -= 1

    return count


print(count_divisors(36))


