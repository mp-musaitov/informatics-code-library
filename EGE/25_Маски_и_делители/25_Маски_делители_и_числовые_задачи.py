# БЛОК 1. МАСКА + ДЕЛИМОСТЬ — FNMATCH
# ============================================================
from fnmatch import fnmatchcase

mask = '3?12?14*5'
k = 1917
limit = 10 ** 10

for n in range(k, limit + 1, k):
    if fnmatchcase(str(n), mask):
        print(n, n // k)


# ============================================================
# БЛОК 2. МАСКА + ДЕЛИМОСТЬ — REGEX
# ============================================================
import re

pattern = re.compile(r'3\d12\d14\d*5')

for n in range(1917, 10 ** 10 + 1, 1917):
    if pattern.fullmatch(str(n)):
        print(n, n // 1917)


