# БЛОК 3. ВСЕ ДЕЛИТЕЛИ ЧИСЛА
# ============================================================
def divisors(n):
    d = set()

    for i in range(1, int(n ** 0.5) + 1):
        if n % i == 0:
            d.add(i)
            d.add(n // i)

    return sorted(d)


print(divisors(100))


# ============================================================
# БЛОК 4. ДЕЛИТЕЛИ БЕЗ 1 И САМОГО ЧИСЛА
# ============================================================
def divisors_without_edges(n):
    d = set()

    for i in range(2, int(n ** 0.5) + 1):
        if n % i == 0:
            d.add(i)
            d.add(n // i)

    d.discard(n)

    return sorted(d)


print(divisors_without_edges(100))


