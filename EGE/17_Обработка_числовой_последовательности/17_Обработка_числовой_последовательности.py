# БЛОК 7. ДВА РАЗЛИЧНЫХ ЭЛЕМЕНТА — НЕ ОБЯЗАТЕЛЬНО СОСЕДНИХ
# ============================================================
# Условие:
# Под парой понимаются два различных элемента последовательности.
# Они могут находиться в любых позициях.
# Различные элементы = разные позиции, значения могут совпадать.

with open('17.txt') as f:
    a = [int(x) for x in f]

count = 0
best = None

for i in range(len(a)):
    for j in range(i + 1, len(a)):
        x = a[i]
        y = a[j]

        if (x + y) % 120 == 0:
            count += 1
            value = x + y

            if best is None or value > best:
                best = value

print(count, best)


