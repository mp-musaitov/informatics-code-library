# БЛОК 3. СОСЕДНИЕ ТРОЙКИ
# ============================================================
# Условие:
# Нужно рассмотреть все тройки соседних элементов.
# Например: ровно два элемента четырёхзначные
# и оканчиваются на 3.

with open('17.txt') as f:
    a = [int(x) for x in f]

for i in range(len(a) - 2):
    t = a[i:i + 3]

    b = [x for x in t
         if 1000 <= abs(x) <= 9999 and abs(x) % 10 == 3]

    if len(b) == 2:
        print(t)


