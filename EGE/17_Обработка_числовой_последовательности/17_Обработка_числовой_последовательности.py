# ============================================================
# БЛОК 5. СЧЁТЧИК + МАКСИМУМ
# ============================================================
# Условие:
# Нужно посчитать подходящие соседние пары
# и найти максимальную сумму среди них.
# Для экстремума используем best = None.

with open('17.txt') as f:
    a = [int(x) for x in f]

count = 0
best = None

for i in range(len(a) - 1):
    t = a[i:i + 2]

    if any(x % 7 == 0 for x in t):
        count += 1
        value = sum(t)

        if best is None or value > best:
            best = value

print(count, best)


