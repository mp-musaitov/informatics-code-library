# БЛОК 6. ХАРАКТЕРИСТИКА ВСЕЙ ПОСЛЕДОВАТЕЛЬНОСТИ
# ============================================================
# Условие:
# Сначала нужно найти характеристику всей последовательности,
# затем использовать её при проверке текущей группы.
# Например: максимальный четырёхзначный элемент,
# оканчивающийся на 3.

with open('17.txt') as f:
    a = [int(x) for x in f]

b = [x for x in a
     if 1000 <= abs(x) <= 9999 and abs(x) % 10 == 3]

m = max(b)

count = 0
best = None

for i in range(len(a) - 2):
    t = a[i:i + 3]

    p = [x for x in t
         if 1000 <= abs(x) <= 9999 and abs(x) % 10 == 3]

    if len(p) == 2 and sum(t) > m:
        count += 1
        value = sum(t)

        if best is None or value > best:
            best = value

print(count, best)


