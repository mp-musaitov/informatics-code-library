# БЛОК 5. ПЕРЕВОД ИЗ ДЕСЯТИЧНОЙ СИСТЕМЫ В СИСТЕМУ p
# ============================================================
# Условие:
# Перевести десятичное число в систему счисления
# с заданным основанием и получить список его цифр.


def to_base(n, base):
    digits = []

    while n > 0:
        digits.append(n % base)
        n //= base

    return digits[::-1]


print(to_base(38, 5))


