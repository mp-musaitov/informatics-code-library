# БЛОК 3. ПОДСЧЁТ ЦИФР В ЗАПИСИ ЧИСЛА
# ============================================================
# Условие:
# Дано большое число.
# Нужно определить, сколько нулей содержится
# в его записи в системе счисления с основанием 7.

n = 7**170 + 7**100 - 100
base = 7
count = 0

while n > 0:
    if n % base == 0:
        count += 1
    n //= base

print(count)


# ============================================================
# БЛОК 4. ПЕРЕБОР ПАРАМЕТРА x ПО КОЛИЧЕСТВУ ЦИФР
# ============================================================
# Условие:
# Найти наибольшее x, не превосходящее 2030,
# при котором в семеричной записи выражения
# 7^170 + 7^100 - x содержится ровно 71 нуль.

for x in range(2030, 0, -1):
    n = 7**170 + 7**100 - x
    count = 0

    while n > 0:
        if n % 7 == 0:
            count += 1
        n //= 7

    if count == 71:
        print(x)
        break


