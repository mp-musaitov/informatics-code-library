# ЕГЭ №2. Логические выражения и таблицы истинности
#
# Основная задача: восстановить порядок переменных в столбцах
# фрагмента таблицы истинности.
#
# Обычно удобнее всего использовать permutations().

from itertools import product, permutations


# ============================================================
# БЛОК 1. ПОЛНАЯ ТАБЛИЦА ИСТИННОСТИ
# ============================================================
# Условие:
# Нужно вывести все наборы значений переменных и значение функции.
#
# Этот блок полезен, если нужно самостоятельно построить
# таблицу истинности или проверить выражение.

for x, y, z, w in product([0, 1], repeat=4):
    f = (x and not y) or (z == w)
    print(x, y, z, w, int(f))


# ============================================================
# БЛОК 2. ВОССТАНОВЛЕНИЕ ПОРЯДКА ПЕРЕМЕННЫХ
# ============================================================
# Условие:
# В таблице есть четыре неизвестных столбца и столбец F.
# Нужно определить, какая переменная соответствует каждому столбцу.
#
# В rows записываем строки из условия:
# первые 4 значения — неизвестные столбцы,
# последнее значение — F.

rows = [
    (0, 1, 0, 1, 1),
    (1, 0, 0, 1, 0),
]

for names in permutations('xyzw'):
    ok = True

    for row in rows:
        values = dict(zip(names, row[:4]))

        x = values['x']
        y = values['y']
        z = values['z']
        w = values['w']

        # Заменить на функцию из конкретного задания
        f = (x and not y) or (z == w)

        if int(f) != row[4]:
            ok = False
            break

    if ok:
        print(*names)


# ============================================================
# БЛОК 3. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# Условие:
# То же восстановление порядка переменных, но запись короче.
#
# a, b, c, d — столбцы таблицы слева направо.
# p — предполагаемый порядок переменных в этих столбцах.

rows = [
    (0, 1, 0, 1, 1),
    (1, 0, 0, 1, 0),
]

for p in permutations('xyzw'):
    flag = True

    for a, b, c, d, F in rows:
        values = dict(zip(p, (a, b, c, d)))
        x, y, z, w = values['x'], values['y'], values['z'], values['w']

        f = (x and not y) or (z == w)

        if f != F:
            flag = False
            break

    if flag:
        print(*p)


# ============================================================
# БЛОК 4. ЕСЛИ В ТАБЛИЦЕ ЕСТЬ ПРОПУСКИ
# ============================================================
# Условие:
# Часть значений в строке таблицы неизвестна.
# Обозначаем неизвестные клетки None и перебираем вместо них 0 и 1.

row = [0, None, 1, None]
unknown = row.count(None)

for bits in product([0, 1], repeat=unknown):
    new_row = row[:]
    j = 0

    for i in range(len(new_row)):
        if new_row[i] is None:
            new_row[i] = bits[j]
            j += 1

    print(new_row)


