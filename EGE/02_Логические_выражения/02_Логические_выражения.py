# БЛОК 4. УДОБНЫЙ КОРОТКИЙ ШАБЛОН БЕЗ ЛИШНИХ СЛОВАРЕЙ
# ============================================================
# Условие:
# Нужно восстановить порядок переменных по строкам таблицы.
#
# Здесь значения неизвестных столбцов сначала связываются
# с именами переменных, после чего проверяется функция.

rows = [
    (0, 1, 0, 1, 1),
    (1, 0, 0, 1, 0),
]

for p in permutations('xyzw'):
    flag = True

    for a, b, c, d, F in rows:
        values = dict(zip(p, (a, b, c, d)))
        x, y, z, w = values['x'], values['y'], values['z'], values['w']

        f = (x and not y) or (z == w)

        if f != F:
            flag = False
            break

    if flag:
        print(*p)


