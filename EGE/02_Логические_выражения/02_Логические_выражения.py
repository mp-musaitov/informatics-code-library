# ============================================================
# БЛОК 1. ПОЛНАЯ ТАБЛИЦА ИСТИННОСТИ
# ============================================================
# Условие:
# Нужно посмотреть все значения функции для всех наборов
# логических переменных.
#
# Этот блок полезен для проверки функции и понимания её поведения.

from itertools import product

for x, y, z, w in product([0, 1], repeat=4):
    f = (x and not y) or (z == w)
    print(x, y, z, w, int(f))


# ============================================================
# БЛОК 2. ВОССТАНОВЛЕНИЕ ПОРЯДКА ПЕРЕМЕННЫХ
# ============================================================
# Условие:
# В таблице есть четыре неизвестных столбца и столбец F.
# Нужно определить, какая переменная соответствует каждому столбцу.
#
# В rows записываем строки из условия:
# первые 4 значения — неизвестные столбцы,
# последнее значение — F.

from itertools import permutations

rows = [
    (0, 1, 0, 1, 1),
    (1, 0, 0, 1, 0),
]

for names in permutations('xyzw'):
    ok = True

    for row in rows:
        values = dict(zip(names, row[:4]))

        x = values['x']
        y = values['y']
        z = values['z']
        w = values['w']

        # Заменить на функцию из конкретного задания
        f = (x and not y) or (z == w)

        if int(f) != row[4]:
            ok = False
            break

    if ok:
        print(*names)


