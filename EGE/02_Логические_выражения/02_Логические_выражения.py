# БЛОК 5. ЕСЛИ В ТАБЛИЦЕ ЕСТЬ ПРОПУСКИ
# ============================================================
# Условие:
# В некоторых вариантах часть клеток таблицы может быть неизвестна.
# Их можно обозначить None и перебрать возможные значения 0 и 1.
#
# Ниже показан общий принцип.

row = [0, None, 1, None]

unknown = row.count(None)

for bits in product([0, 1], repeat=unknown):
    new_row = row[:]
    j = 0

    for i in range(len(new_row)):
        if new_row[i] is None:
            new_row[i] = bits[j]
            j += 1

    print(new_row)


