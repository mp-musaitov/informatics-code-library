# ЕГЭ №20. Теория игр — выигрышная стратегия Пети


# ============================================================
# БЛОК 1. ВСЕ ВОЗМОЖНЫЕ ХОДЫ
# ============================================================
# За один ход можно прибавить 4 к одной куче
# или увеличить одну из куч в 2 раза.

def moves(x, y):
    return (
        (x + 4, y),
        (x, y + 4),
        (x * 2, y),
        (x, y * 2)
    )


# ============================================================
# БЛОК 2. ПОБЕДА ЗА ОДИН ХОД — win1
# ============================================================
# Игрок может выиграть за один ход,
# если существует хотя бы один ход с суммой >= 133.

def win1(x, y):
    return x + y < 133 and any(
        sum(p) >= 133
        for p in moves(x, y)
    )


# ============================================================
# БЛОК 3. ПРОИГРЫШНАЯ ПОЗИЦИЯ — lose1
# ============================================================
# Любой ход игрока приводит к позиции,
# из которой соперник может выиграть за один ход.

def lose1(x, y):
    return x + y < 133 and all(
        win1(*p)
        for p in moves(x, y)
    )


# ============================================================
# БЛОК 4. ПОБЕДА СВОИМ ВТОРЫМ ХОДОМ — win2
# ============================================================
# Игрок не может выиграть сразу,
# но существует ход в проигрышную для соперника позицию.

def win2(x, y):
    return not win1(x, y) and any(
        lose1(*p)
        for p in moves(x, y)
    )


# ============================================================
# БЛОК 5. РЕШЕНИЕ ДЕМОВЕРСИИ ЕГЭ-2027
# ============================================================
# Начальная позиция: (17, S), 1 <= S <= 115.
# Нужно найти два наименьших S.

ans = []

for S in range(1, 116):
    if win2(17, S):
        ans.append(S)

print(*ans[:2])


# ============================================================
# БЛОК 6. ТО ЖЕ БЕЗ ОТДЕЛЬНОЙ ФУНКЦИИ win2
# ============================================================
# Иногда ученику проще видеть условие прямо в цикле.

ans = []

for S in range(1, 116):
    if not win1(17, S) and any(
        lose1(*p)
        for p in moves(17, S)
    ):
        ans.append(S)

print(*ans[:2])


# ============================================================
# БЛОК 7. ПРОВЕРКА ОДНОГО ЗНАЧЕНИЯ S
# ============================================================
# Удобно для разбора конкретной позиции.

S = 28

print('S =', S)
print('Петя может выиграть первым ходом:', win1(17, S))
print('Петя может гарантированно выиграть вторым ходом:', win2(17, S))


