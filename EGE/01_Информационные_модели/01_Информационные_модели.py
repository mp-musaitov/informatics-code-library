# БЛОК 3. ЕСЛИ В ТАБЛИЦЕ УКАЗАНЫ ДЛИНЫ ДОРОГ
# ============================================================
# Условие:
# После определения соответствия нужно найти длину дороги
# между двумя заданными вершинами, например A и D.
#
# В таблице удобно хранить длины дорог в словаре.

roads = {
    frozenset((1, 2)): 12,
    frozenset((1, 4)): 17,
    frozenset((2, 3)): 25,
    frozenset((3, 4)): 9
}

# Допустим, после сопоставления получили:
correspondence = {
    'A': 1,
    'B': 2,
    'C': 4,
    'D': 3
}

x = correspondence['A']
y = correspondence['D']

print(roads[frozenset((x, y))])


