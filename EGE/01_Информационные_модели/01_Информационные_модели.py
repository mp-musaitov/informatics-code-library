# Это помогает начать сопоставление графа с таблицей.


graph = {
    'A': ['B', 'C', 'D'],
    'B': ['A', 'D'],
    'C': ['A', 'D'],
    'D': ['A', 'B', 'C']
}

for v in graph:
    print(v, len(graph[v]))


