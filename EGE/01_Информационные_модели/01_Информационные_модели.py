# БЛОК 2. ПОЛНЫЙ ПЕРЕБОР СООТВЕТСТВИЙ
# ============================================================
# Условие:
# Вершины графа обозначены буквами, а в таблице — номерами.
# Нужно определить, какая буква соответствует какому номеру.
#
# Идея:
# перебираем все перестановки номеров и оставляем только те,
# при которых все рёбра графа совпадают со связями в таблице.

from itertools import permutations

letters = ['A', 'B', 'C', 'D']
numbers = [1, 2, 3, 4]

# Рёбра графа из рисунка
edges_graph = {
    frozenset(('A', 'B')),
    frozenset(('A', 'C')),
    frozenset(('B', 'D')),
    frozenset(('C', 'D'))
}

# Связи из таблицы
edges_table = {
    frozenset((1, 2)),
    frozenset((1, 4)),
    frozenset((2, 3)),
    frozenset((3, 4))
}

for p in permutations(numbers):
    d = dict(zip(letters, p))

    converted = set()

    for edge in edges_graph:
        a, b = edge
        converted.add(frozenset((d[a], d[b])))

    if converted == edges_table:
        print(d)


