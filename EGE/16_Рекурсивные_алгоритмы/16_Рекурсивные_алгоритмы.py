# ============================================================
# БЛОК 1. ПРОСТАЯ РЕКУРСИЯ С ОДНИМ ПРЕДЫДУЩИМ ЗНАЧЕНИЕМ
# ============================================================
# Условие:
# F(1) = 1
# F(n) = n * F(n - 1), n > 1


def f(n):
    if n == 1:
        return 1
    return n * f(n - 1)


print(f(5))


# ============================================================
# БЛОК 2. ДЕМОВЕРСИОННЫЙ ТИП: СОКРАЩАЕМ, А НЕ СЧИТАЕМ F(3038)
# ============================================================
# Условие:
# F(1) = 1
# F(n) = n * F(n - 1)
# Найти:
# (F(3038) + 5 * F(3037)) / F(3036)
#
# Раскрываем только нужные значения:
# F(3038) = 3038 * F(3037)
# F(3037) = 3037 * F(3036)
#
# После сокращения остаётся обычное выражение.

answer = (3038 + 5) * 3037
print(answer)


# ============================================================
# БЛОК 3. РЕКУРСИЯ С НЕСКОЛЬКИМИ ВЕТВЯМИ
# ============================================================
# Условие:
# F(n) = n, если n < 15
# F(n) = (n + 6) * F(n - 8), если n >= 15 и n чётное
# F(n) = (n + 4) * F(n - 6), если n >= 15 и n нечётное


def f(n):
    if n < 15:
        return n

    if n % 2 == 0:
        return (n + 6) * f(n - 8)

    return (n + 4) * f(n - 6)


print(f(25))


# ============================================================
# БЛОК 4. ДВА РЕКУРСИВНЫХ ВЫЗОВА
# ============================================================
# Условие:
# F(1) = 1
# F(2) = 2
# F(n) = 2 * F(n - 1) + (n - 2) * F(n - 2)


def f(n):
    if n == 1:
        return 1
    if n == 2:
        return 2

    return 2 * f(n - 1) + (n - 2) * f(n - 2)


print(f(6))


# ============================================================
# БЛОК 5. ТО ЖЕ С МЕМОИЗАЦИЕЙ
# ============================================================
# Условие:
# При нескольких рекурсивных вызовах одни и те же F(n)
# могут вычисляться много раз. Запоминаем результаты.

from functools import lru_cache


@lru_cache(None)
def f(n):
    if n == 1:
        return 1
    if n == 2:
        return 2

    return 2 * f(n - 1) + (n - 2) * f(n - 2)


print(f(30))


# ============================================================
# БЛОК 6. КУСОЧНО ЗАДАННАЯ ФУНКЦИЯ
# ============================================================
# Условие:
# F(n) = 3, если n <= 30
# F(n) = -3 + 2F(n - 29), если 30 < n <= 250
# F(n) = 2 + F(n - 43), если 250 < n <= 900
# F(n) = 3 + F(n - 62), если n > 900


def f(n):
    if n <= 30:
        return 3
    if n <= 250:
        return -3 + 2 * f(n - 29)
    if n <= 900:
        return 2 + f(n - 43)
    return 3 + f(n - 62)


print(f(1000))


# ============================================================
# БЛОК 7. ДВЕ ВЗАИМОСВЯЗАННЫЕ ФУНКЦИИ
# ============================================================
# Условие:
# F и G вызывают друг друга.


def f(n):
    if n == 1:
        return 1
    return n + g(n - 1)


def g(n):
    if n == 1:
        return 1
    return 2 * n + f(n - 1)


print(f(5))
print(g(5))


# ============================================================
# БЛОК 8. РЕКУРСИЮ МОЖНО ЗАМЕНИТЬ ЦИКЛОМ
# ============================================================
# Условие:
# F(1) = 1
# F(n) = F(n - 1) + n
#
# Если нужны сами значения, а рекурсия слишком глубокая,
# иногда проще считать последовательно циклом.

value = 1

for n in range(2, 101):
    value += n

print(value)


# ============================================================
# БЛОК 9. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# 1. Сначала найди базовый случай.
# 2. Перепиши рекурсивное правило буквально.
# 3. Если в ответе дробь из F(...), сначала попробуй сократить.
# 4. Если рекурсия ветвится, подумай о lru_cache.


def f(n):
    if n <= 2:
        return 1

    return f(n - 1) + f(n - 2)


print(f(10))


