# ЕГЭ №22. Параллельные процессы

# ============================================================
# БЛОК 1. ДАННЫЕ О ПРОЦЕССАХ
# ============================================================
# Формат:
# ID: (длительность, [зависимости])

p = {
    1: (3, []),
    2: (4, [1]),
    3: (2, [2, 4]),
    4: (5, []),
    5: (8, [1, 4]),
    6: (3, [1]),
}


# ============================================================
# БЛОК 2. НАЧАЛО И КОНЕЦ КАЖДОГО ПРОЦЕССА
# ============================================================
start = {}
end = {}


def calc(i):
    if i in end:
        return

    duration, deps = p[i]

    # Сначала рассчитываем все процессы,
    # от которых зависит текущий.
    for d in deps:
        calc(d)

    if not deps:
        start[i] = 1
    else:
        start[i] = max(end[d] for d in deps) + 1

    end[i] = start[i] + duration - 1


for i in p:
    calc(i)

print(start)
print(end)


# ============================================================
# БЛОК 3. КАКИЕ ПРОЦЕССЫ РАБОТАЮТ В МОМЕНТ t
# ============================================================
t = 7

active = [
    i for i in p
    if start[i] <= t <= end[i]
]

print(active)
print(len(active))


# ============================================================
# БЛОК 4. КОЛИЧЕСТВО ПРОЦЕССОВ В МОМЕНТ t
# ============================================================
t = 7

count = sum(
    start[i] <= t <= end[i]
    for i in p
)

print(count)


# ============================================================
# БЛОК 5. ВРЕМЯ ЗАВЕРШЕНИЯ ВСЕХ ПРОЦЕССОВ
# ============================================================
finish_time = max(end.values())

print(finish_time)


# ============================================================
# БЛОК 6. ПРОЦЕССЫ, КОТОРЫЕ НАЧИНАЮТСЯ ПОСЛЕДНИМИ
# ============================================================
last_start = max(start.values())

last_processes = [
    i for i in p
    if start[i] == last_start
]

print(last_start)
print(last_processes)


# ============================================================
# БЛОК 7. СКОЛЬКО ПРОЦЕССОВ ЗАВЕРШИЛОСЬ К МОМЕНТУ t
# ============================================================
t = 7

count_finished = sum(
    end[i] <= t
    for i in p
)

print(count_finished)


# ============================================================
# БЛОК 8. МАКСИМАЛЬНОЕ ЧИСЛО ОДНОВРЕМЕННЫХ ПРОЦЕССОВ
# ============================================================
max_count = 0
best_t = []

for t in range(1, max(end.values()) + 1):
    count = sum(
        start[i] <= t <= end[i]
        for i in p
    )

    if count > max_count:
        max_count = count
        best_t = [t]
    elif count == max_count:
        best_t.append(t)

print(max_count)
print(best_t)


# ============================================================
# БЛОК 9. КОРОТКИЙ ШАБЛОН ДЛЯ ЕГЭ
# ============================================================
# После заполнения словаря p этот код автоматически
# вычисляет расписание и число процессов на нужной миллисекунде.

start = {}
end = {}


def calc(i):
    if i in end:
        return

    duration, deps = p[i]

    for d in deps:
        calc(d)

    start[i] = 1 if not deps else max(end[d] for d in deps) + 1
    end[i] = start[i] + duration - 1


for i in p:
    calc(i)

t = 7

print(sum(
    start[i] <= t <= end[i]
    for i in p
))


# ============================================================
# ПАМЯТКА
# ============================================================
# Независимый процесс:
# start = 1
#
# Зависимый процесс:
# start = max(end зависимостей) + 1
#
# Конец процесса:
# end = start + duration - 1
#
# Процесс работает на t-й миллисекунде:
# start <= t <= end
#
# Независимые процессы выполняются параллельно.
