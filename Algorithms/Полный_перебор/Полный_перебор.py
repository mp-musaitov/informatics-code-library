# 5. ПОИСК ЛУЧШЕГО ВАРИАНТА
# ============================================================

best = None
best_pair = None

for a in range(1, 20):
    for b in range(1, 20):
        if a + b == 20:
            value = a * b

            if best is None or value > best:
                best = value
                best_pair = (a, b)

print(best_pair)
print(best)


