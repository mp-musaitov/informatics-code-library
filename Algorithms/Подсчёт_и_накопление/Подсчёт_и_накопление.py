# ============================================================
# 1. ПОДСЧЁТ ВСЕХ ЭЛЕМЕНТОВ
# ============================================================

numbers = [8, 3, 12, 5, 17, 2]

count = 0

for x in numbers:
    count += 1

print(count)


# ============================================================
# 2. ПОДСЧЁТ ЭЛЕМЕНТОВ ПО УСЛОВИЮ
# ============================================================

count = 0

for x in numbers:
    if x % 2 == 0:
        count += 1

print(count)


# ============================================================
# 3. НАКОПЛЕНИЕ СУММЫ
# ============================================================

total = 0

for x in numbers:
    total += x

print(total)


# ============================================================
# 4. КОЛИЧЕСТВО И СУММА ПО УСЛОВИЮ
# ============================================================

numbers = [-4, 7, 0, 12, -3, 5]

count = 0
total = 0

for x in numbers:
    if x > 0:
        count += 1
        total += x

print(count)
print(total)


# ============================================================
# 5. СРЕДНЕЕ ПОДХОДЯЩИХ ЭЛЕМЕНТОВ
# ============================================================

count = 0
total = 0

for x in numbers:
    if x > 0:
        count += 1
        total += x

if count > 0:
    average = total / count
    print(average)
else:
    print('Подходящих значений нет')


# ============================================================
# 6. НЕСКОЛЬКО СЧЁТЧИКОВ
# ============================================================

numbers = [-4, 7, 0, 12, -3, 0, 5]

positive = 0
negative = 0
zeros = 0

for x in numbers:
    if x > 0:
        positive += 1
    elif x < 0:
        negative += 1
    else:
        zeros += 1

print(positive)
print(negative)
print(zeros)


# ============================================================
# 7. НАКОПЛЕНИЕ ПРОИЗВЕДЕНИЯ
# ============================================================

numbers = [2, 3, 4, 5]

product = 1

for x in numbers:
    product *= x

print(product)


