# Подсчёт символов в строке

# Задача: считать символы, искать самые частые символы
# и проверять различные условия для символов строки.

# ------------------------------------------------------------
# 1. Посчитать конкретный символ
text = 'информатика'
count = 0

for symbol in text:
    if symbol == 'а':
        count += 1

print(count)  # 2

# ------------------------------------------------------------
# 2. Короткий вариант через count()
text = 'информатика'
print(text.count('а'))  # 2

# count() подходит, когда нужно посчитать конкретный символ
# или конкретную подстроку.

# ------------------------------------------------------------
# 3. Посчитать символы, удовлетворяющие условию
text = 'ЕГЭ 2026!'
count = 0

for symbol in text:
    if symbol.isdigit():
        count += 1

print(count)  # 4

# ------------------------------------------------------------
# 4. Посчитать буквы
text = 'Python 3.14'
count = 0

for symbol in text:
    if symbol.isalpha():
        count += 1

print(count)  # 6

# ------------------------------------------------------------
# 5. Посчитать символы из заданного набора
text = 'информатика'
vowels = 'аеёиоуыэюя'
count = 0

for symbol in text:
    if symbol in vowels:
        count += 1

print(count)

# ------------------------------------------------------------
# 6. Частоты всех символов через словарь
text = 'абракадабра'
frequency = {}

for symbol in text:
    if symbol in frequency:
        frequency[symbol] += 1
    else:
        frequency[symbol] = 1

print(frequency)

# ------------------------------------------------------------
# 7. Более короткий вариант со словарём
text = 'абракадабра'
frequency = {}

for symbol in text:
    frequency[symbol] = frequency.get(symbol, 0) + 1

print(frequency)

# ------------------------------------------------------------
# 8. Самый частый символ
text = 'абракадабра'
frequency = {}

for symbol in text:
    frequency[symbol] = frequency.get(symbol, 0) + 1

most_frequent = max(frequency, key=frequency.get)
print(most_frequent, frequency[most_frequent])  # а 5

# ------------------------------------------------------------
# 9. Подсчитать символы по индексам
text = 'ABC123XYZ'
count = 0

for i in range(len(text)):
    if text[i].isdigit():
        count += 1

print(count)  # 3

# Этот способ нужен, когда важна не только буква,
# но и её позиция или соседние символы.

# ------------------------------------------------------------
# 10. Подсчёт символов в файле
count = 0

with open('input.txt', 'r', encoding='utf-8') as file:
    text = file.read()

for symbol in text:
    if symbol == 'A':
        count += 1

print(count)

