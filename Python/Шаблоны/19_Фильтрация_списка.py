# Фильтрация списка

# Фильтрация — отбор только тех элементов списка,
# которые удовлетворяют заданному условию.

# ------------------------------------------------------------
# 1. Понятный вариант через обычный цикл
numbers = [12, 7, 18, 5, 24, 9]
result = []

for number in numbers:
    if number % 2 == 0:
        result.append(number)

print(result)  # [12, 18, 24]

# ------------------------------------------------------------
# 2. То же самое через генератор списка
numbers = [12, 7, 18, 5, 24, 9]
result = [number for number in numbers if number % 2 == 0]

print(result)  # [12, 18, 24]

# ------------------------------------------------------------
# 3. Фильтрация по нескольким условиям
numbers = [5, 12, 18, 21, 24, 30, 37]

result = [
    number
    for number in numbers
    if number % 2 == 0 and number > 15
]

print(result)  # [18, 24, 30]

# ------------------------------------------------------------
# 4. Отбор строк по длине
words = ['кот', 'информатика', 'код', 'python', 'егэ']

long_words = [word for word in words if len(word) >= 5]
print(long_words)  # ['информатика', 'python']

# ------------------------------------------------------------
# 5. Отбор строк по содержимому
words = ['python', 'pascal', 'pandas', 'code']

result = [word for word in words if word.startswith('p')]
print(result)  # ['python', 'pascal', 'pandas']

# ------------------------------------------------------------
# 6. Отбор с преобразованием
numbers = [1, 2, 3, 4, 5, 6]

# Берём только чётные и сразу возводим их в квадрат.
result = [number ** 2 for number in numbers if number % 2 == 0]
print(result)  # [4, 16, 36]

# ------------------------------------------------------------
# 7. Сохранить индексы подходящих элементов
numbers = [10, 15, 20, 25, 30]
indices = []

for i in range(len(numbers)):
    if numbers[i] % 20 == 0:
        indices.append(i)

print(indices)  # [2]

# ------------------------------------------------------------
# 8. Фильтрация с enumerate()
numbers = [10, 15, 20, 25, 30]

result = []
for i, number in enumerate(numbers):
    if number >= 20:
        result.append((i, number))

print(result)  # [(2, 20), (3, 25), (4, 30)]

# ------------------------------------------------------------
# 9. Удалять элементы из списка во время обхода — опасно
numbers = [1, 2, 3, 4, 5, 6]

# Плохой подход:
# for number in numbers:
#     if number % 2 == 0:
#         numbers.remove(number)

# Из-за изменения длины списка часть элементов можно пропустить.

# Лучше создать новый список:
numbers = [1, 2, 3, 4, 5, 6]
numbers = [number for number in numbers if number % 2 != 0]
print(numbers)  # [1, 3, 5]

# ------------------------------------------------------------
# 10. Фильтрация данных из файла
result = []

with open('input.txt', 'r', encoding='utf-8') as file:
    for line in file:
        number = int(line)
        if number > 0:
            result.append(number)

print(result)

# ------------------------------------------------------------
# Частые ошибки

# 1. Изменять исходный список прямо во время перебора.
# 2. Забыть append() в обычном цикле.
# 3. Перепутать условие отбора и условие исключения.
# 4. В генераторе списка поставить if не на то место.
# 5. Забыть, что результат фильтрации может оказаться пустым списком.

