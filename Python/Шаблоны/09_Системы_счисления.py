# Частые ошибки

# 1. Забыть [2:] после bin(), oct() или hex(), если префикс не нужен.
# 2. Путать основание системы с количеством цифр в записи.
# 3. Забыть, что результат bin(), oct(), hex() и to_base() — строка.
# 4. Использовать int(digit) для буквенной цифры A, B, C...
# 5. В собственной функции перевода забыть отдельный случай n == 0.
# 6. Собирать остатки в прямом порядке: они появляются справа налево.

