# Системы счисления

# Шаблоны перевода чисел и работы с записью числа в разных системах счисления.

# ------------------------------------------------------------
# 1. Из двоичной системы в десятичную
binary = '101101'
number = int(binary, 2)
print(number)  # 45

# int(строка, основание) переводит запись числа в десятичное значение.

# 2. Из восьмеричной системы в десятичную
octal = '157'
print(int(octal, 8))  # 111

# 3. Из шестнадцатеричной системы в десятичную
hexadecimal = '2AF'
print(int(hexadecimal, 16))  # 687

# 4. Из десятичной системы в двоичную
n = 45
print(bin(n))     # 0b101101
print(bin(n)[2:]) # 101101

# 5. Из десятичной в восьмеричную
n = 111
print(oct(n))     # 0o157
print(oct(n)[2:]) # 157

# 6. Из десятичной в шестнадцатеричную
n = 687
print(hex(n))     # 0x2af
print(hex(n)[2:]) # 2af

# ------------------------------------------------------------
# 7. Универсальный перевод из десятичной системы в основание от 2 до 36

def to_base(n, base):
    digits = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'

    if n == 0:
        return '0'

    result = ''

    while n > 0:
        result = digits[n % base] + result
        n //= base

    return result

print(to_base(45, 2))   # 101101
print(to_base(100, 3))  # 10201
print(to_base(687, 16)) # 2AF

# Почему работает:
# остаток n % base даёт очередную цифру справа,
# а n //= base удаляет эту цифру из дальнейшего рассмотрения.

# ------------------------------------------------------------
# 8. Перевод в систему счисления с основанием больше 10

print(to_base(255, 16))  # FF

# Цифры после 9 обозначаются буквами:
# A = 10, B = 11, ..., F = 15 и т.д.

# ------------------------------------------------------------
# 9. Подсчитать цифры в записи числа

n = 100
representation = to_base(n, 3)
print(representation)           # 10201
print(representation.count('0'))  # 2

# ------------------------------------------------------------
# 10. Сумма цифр записи числа

n = 100
representation = to_base(n, 3)

total = 0
for digit in representation:
    total += int(digit)

print(total)  # 4

# Этот простой вариант подходит, если основание <= 10.
# При основаниях выше 10 встречаются буквы, и int('A') уже не сработает.

# ------------------------------------------------------------
# 11. Сумма значений цифр при основании до 36

def digit_value(symbol):
    digits = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'
    return digits.index(symbol.upper())

representation = '2AF'
total = 0
for symbol in representation:
    total += digit_value(symbol)
print(total)  # 2 + 10 + 15 = 27

