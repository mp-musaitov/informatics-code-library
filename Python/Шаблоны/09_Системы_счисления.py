# 12. Частый шаблон ЕГЭ: построить большое число и исследовать его запись

number = 2 ** 20 + 2 ** 10 - 1
binary = bin(number)[2:]

print(binary.count('1'))

# Вместо двоичной системы может понадобиться другое основание:
