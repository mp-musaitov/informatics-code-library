# ------------------------------------------------------------
# 13. Замена цифр в записи

number = 3 ** 10 + 3 ** 5
representation = to_base(number, 3)

representation = representation.replace('2', '0')
print(representation)

# После перевода запись — обычная строка,
# поэтому к ней можно применять count(), replace(), индексы и срезы.

# ------------------------------------------------------------
# 14. Проверка записи числа на условие

number = 100
representation = to_base(number, 3)

if representation.count('1') > representation.count('2'):
    print('Единиц больше')

