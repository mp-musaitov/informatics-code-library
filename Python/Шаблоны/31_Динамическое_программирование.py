# Динамическое программирование

# Динамическое программирование (DP) используют,
# когда результат для текущего состояния зависит от уже вычисленных состояний.
# Вместо повторного пересчёта мы сохраняем промежуточные ответы.

# ------------------------------------------------------------
# 1. Простейший пример: числа Фибоначчи

n = 10

dp = [0] * (n + 1)
dp[0] = 0
dp[1] = 1

for i in range(2, n + 1):
    dp[i] = dp[i - 1] + dp[i - 2]

print(dp[n])  # 55

# Здесь dp[i] — ответ для состояния i.

# ------------------------------------------------------------
# 2. Количество способов попасть в точку n
# Разрешены шаги +1 и +2.

n = 6

dp = [0] * (n + 1)
dp[0] = 1

for i in range(1, n + 1):
    dp[i] += dp[i - 1]

    if i >= 2:
        dp[i] += dp[i - 2]

print(dp[n])

# ------------------------------------------------------------
# 3. Количество программ исполнителя
# Разрешены команды +1 и *2.

start = 1
finish = 20

dp = [0] * (finish + 1)
dp[start] = 1

for x in range(start, finish + 1):
    if x + 1 <= finish:
        dp[x + 1] += dp[x]

    if x * 2 <= finish:
        dp[x * 2] += dp[x]

print(dp[finish])

# Такой подход полезен для задач с исполнителями,
# когда нужно посчитать число путей между значениями.

# ------------------------------------------------------------
# 4. Запрещённая точка

start = 1
finish = 20
forbidden = 10

dp = [0] * (finish + 1)
dp[start] = 1

for x in range(start, finish + 1):
    if x == forbidden:
        dp[x] = 0
        continue

    if x + 1 <= finish and x + 1 != forbidden:
        dp[x + 1] += dp[x]

    if x * 2 <= finish and x * 2 != forbidden:
        dp[x * 2] += dp[x]

print(dp[finish])

# ------------------------------------------------------------
# 5. Обязательная точка
# Нужно пройти через middle.

start = 1
middle = 10
finish = 20

# Если пути до middle и после middle независимы,
# число программ можно перемножить.

# Для наглядности используем функцию.
def count_paths(start, finish):
    dp = [0] * (finish + 1)
    dp[start] = 1

    for x in range(start, finish + 1):
        if x + 1 <= finish:
            dp[x + 1] += dp[x]

        if x * 2 <= finish:
            dp[x * 2] += dp[x]

    return dp[finish]

answer = count_paths(start, middle) * count_paths(middle, finish)
print(answer)

# ------------------------------------------------------------
# 6. Минимальная стоимость пути
# Например, стоимость перехода в каждую клетку задана числом.

cost = [0, 5, 2, 7, 3, 4]
# Индексы 1..5 — клетки, cost[0] не используется.

n = 5
INF = 10 ** 18

dp = [INF] * (n + 1)
dp[1] = cost[1]

for i in range(2, n + 1):
    best = dp[i - 1]

    if i >= 3:
        best = min(best, dp[i - 2])

    dp[i] = best + cost[i]

print(dp[n])

# ------------------------------------------------------------
# 7. Максимальная сумма по пути

values = [0, 4, 2, 7, 1, 8]
n = 5

dp = [0] * (n + 1)
dp[1] = values[1]

for i in range(2, n + 1):
    best = dp[i - 1]

    if i >= 3:
        best = max(best, dp[i - 2])

    dp[i] = best + values[i]

print(dp[n])

# ------------------------------------------------------------
# 8. DP без хранения всей таблицы
# Для Фибоначчи нужны только два предыдущих значения.

n = 10

a = 0
b = 1

for _ in range(n):
    a, b = b, a + b

print(a)  # 55

# Такой вариант экономит память.

