# 9. Как распознать задачу на DP

# Частые признаки:
# - нужно посчитать количество путей или способов;
# - нужно найти минимум или максимум;
# - ответ для текущего состояния зависит от предыдущих;
# - одинаковые промежуточные состояния возникают много раз;
# - полный перебор слишком велик.

