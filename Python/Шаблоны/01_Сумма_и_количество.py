# Сумма, количество и среднее

# Этот шаблон подходит для задач, где нужно:
# - посчитать количество элементов, удовлетворяющих условию;
# - найти их сумму;
# - при необходимости вычислить среднее значение.

# --------------------------------------------------
# 1. Сумма всех элементов

numbers = [10, 20, 30, 40]

summa = 0
for number in numbers:
    summa += number

print(summa)  # 100

# Короткий вариант:
print(sum(numbers))  # 100


# --------------------------------------------------
# 2. Количество элементов

numbers = [5, 8, 12, 7, 14, 3]

count = 0
for number in numbers:
    if number % 2 == 0:
        count += 1

print(count)  # 3

# Здесь мы считаем количество чётных чисел.


# --------------------------------------------------
# 3. Сумма элементов, удовлетворяющих условию

numbers = [5, 8, 12, 7, 14, 3]

summa = 0
for number in numbers:
    if number % 2 == 0:
        summa += number

print(summa)  # 34


# --------------------------------------------------
# 4. Одновременно количество и сумма

numbers = [5, 8, 12, 7, 14, 3]

count = 0
summa = 0

for number in numbers:
    if number % 2 == 0:
        count += 1
        summa += number

print(count, summa)  # 3 34

# Это один из самых частых шаблонов в задачах ЕГЭ:
# внутри if можно поставить любое нужное условие.


# --------------------------------------------------
# 5. Среднее значение подходящих элементов

numbers = [5, 8, 12, 7, 14, 3]

count = 0
summa = 0

for number in numbers:
    if number % 2 == 0:
        count += 1
        summa += number

if count > 0:
    average = summa / count
    print(average)
else:
    print('Подходящих элементов нет')

# Важно сначала проверить count > 0,
# иначе при отсутствии подходящих элементов возникнет деление на ноль.


# --------------------------------------------------
# 6. Ввод последовательности с клавиатуры

numbers = list(map(int, input('Введите числа через пробел: ').split()))

count = 0
summa = 0

for number in numbers:
    if number > 0:
        count += 1
        summa += number

print('Количество положительных:', count)
print('Сумма положительных:', summa)


# --------------------------------------------------
# 7. Короткие варианты через sum()

numbers = [5, 8, 12, 7, 14, 3]

# Сумма чётных чисел:
summa = sum(number for number in numbers if number % 2 == 0)
print(summa)  # 34

# Количество чётных чисел:
count = sum(1 for number in numbers if number % 2 == 0)
print(count)  # 3

# Для начинающих цикл for обычно понятнее,
# но такие короткие записи тоже часто встречаются в решениях.


