# Сортировка по условию

# В Python для сортировки чаще всего используются:
# sort()   — изменяет исходный список;
# sorted() — создаёт новый отсортированный список.

# ------------------------------------------------------------
# 1. Обычная сортировка по возрастанию
numbers = [7, 2, 9, 1, 5]
numbers.sort()
print(numbers)  # [1, 2, 5, 7, 9]

# ------------------------------------------------------------
# 2. По убыванию
numbers = [7, 2, 9, 1, 5]
numbers.sort(reverse=True)
print(numbers)  # [9, 7, 5, 2, 1]

# ------------------------------------------------------------
# 3. sorted() не меняет исходный список
numbers = [7, 2, 9, 1, 5]
result = sorted(numbers)

print(result)   # [1, 2, 5, 7, 9]
print(numbers)  # [7, 2, 9, 1, 5]

# ------------------------------------------------------------
# 4. Сортировка строк по длине
words = ['кот', 'информатика', 'python', 'код']

words.sort(key=len)
print(words)  # ['кот', 'код', 'python', 'информатика']

# key= задаёт правило, по которому сравниваются элементы.

# ------------------------------------------------------------
# 5. Сортировка чисел по последней цифре
numbers = [123, 54, 81, 47, 36]

numbers.sort(key=lambda number: number % 10)
print(numbers)  # [81, 123, 54, 36, 47]

# Здесь сравниваются не сами числа,
# а значения number % 10.

# ------------------------------------------------------------
# 6. Сортировка по абсолютному значению
numbers = [-20, 5, -3, 12, -8]

numbers.sort(key=abs)
print(numbers)  # [-3, 5, -8, 12, -20]

# ------------------------------------------------------------
# 7. Сортировка пар по второму элементу
pairs = [(1, 50), (2, 10), (3, 30)]

pairs.sort(key=lambda pair: pair[1])
print(pairs)  # [(2, 10), (3, 30), (1, 50)]

# ------------------------------------------------------------
# 8. Сортировка по нескольким критериям
students = [
    ('Адам', 85),
    ('Али', 95),
    ('Муса', 85),
    ('Иса', 95),
]

# Сначала по баллу, затем по имени.
students.sort(key=lambda item: (item[1], item[0]))
print(students)

# Кортеж в key сравнивается по порядку:
# сначала первый критерий, при равенстве — второй.

# ------------------------------------------------------------
# 9. Один критерий по убыванию, другой по возрастанию
students = [
    ('Адам', 85),
    ('Али', 95),
    ('Муса', 85),
    ('Иса', 95),
]

# Балл — по убыванию, имя — по возрастанию.
students.sort(key=lambda item: (-item[1], item[0]))
print(students)

# Минус перед числовым критерием разворачивает его порядок.

# ------------------------------------------------------------
# 10. Сортировка строк без учёта регистра
words = ['Python', 'apple', 'Code', 'banana']

words.sort(key=str.lower)
print(words)

# ------------------------------------------------------------
# 11. Получить несколько наибольших после сортировки
numbers = [12, 4, 30, 9, 25, 18]

result = sorted(numbers, reverse=True)
print(result[:3])  # [30, 25, 18]

# Для очень больших данных, когда нужны только 1–2 максимума,
# сортировать весь список не всегда выгодно.

# ------------------------------------------------------------
# Частые ошибки

# 1. Писать result = numbers.sort().
#    sort() возвращает None, а не отсортированный список.
# 2. Забыть, что sort() изменяет исходный список.
# 3. Путать key= с условием фильтрации: key не удаляет элементы.
# 4. В lambda обращаться не к тому индексу элемента.
# 5. Забыть reverse=True, когда нужен обратный порядок.

# ------------------------------------------------------------
# Универсальные шаблоны

# По одному критерию:
# data.sort(key=lambda x: ...)

# По нескольким критериям:
# data.sort(key=lambda x: (критерий1, критерий2))

# Не менять исходный список:
# result = sorted(data, key=lambda x: ...)
