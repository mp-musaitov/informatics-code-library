# Замена и обработка строк

# В задачах строки часто нужно очищать, заменять фрагменты,
# разбивать на части или собирать заново.

# ------------------------------------------------------------
# 1. replace() — заменить все вхождения
text = 'кот кот кот'
new_text = text.replace('кот', 'пёс')
print(new_text)  # пёс пёс пёс

# Исходная строка не меняется:
print(text)  # кот кот кот

# ------------------------------------------------------------
# 2. Заменить ограниченное количество вхождений
text = 'AAAAA'
print(text.replace('A', 'B', 2))  # BBAAA

# Третий аргумент — максимальное число замен.

# ------------------------------------------------------------
# 3. Удаление фрагмента через replace()
text = '12-34-56'
text = text.replace('-', '')
print(text)  # 123456

# ------------------------------------------------------------
# 4. strip(), lstrip(), rstrip()
text = '   Python   '

print(text.strip())   # убрать пробелы по краям
print(text.lstrip())  # только слева
print(text.rstrip())  # только справа

# ------------------------------------------------------------
# 5. Изменение регистра
text = 'PyThOn'
print(text.lower())  # python
print(text.upper())  # PYTHON

# Удобно для сравнения без учёта регистра:
answer = 'Да'
if answer.lower() == 'да':
    print('Принято')

# ------------------------------------------------------------
# 6. split() — разбить строку на части
text = '10 20 30 40'
parts = text.split()
print(parts)  # ['10', '20', '30', '40']

# ------------------------------------------------------------
# 7. split() с конкретным разделителем
text = 'Иванов;Петров;Сидоров'
names = text.split(';')
print(names)

# ------------------------------------------------------------
# 8. join() — соединить строки
words = ['ЕГЭ', 'по', 'информатике']
text = ' '.join(words)
print(text)  # ЕГЭ по информатике

# ------------------------------------------------------------
# 9. Удаление лишних пробелов между словами
text = 'ЕГЭ    по   информатике'
text = ' '.join(text.split())
print(text)  # ЕГЭ по информатике

# ------------------------------------------------------------
# 10. Построить новую строку по условию
text = 'a1b2c3d4'
result = ''

for symbol in text:
    if not symbol.isdigit():
        result += symbol

print(result)  # abcd

# ------------------------------------------------------------
# 11. Заменить символы по условию
text = 'a1b2c3'
result = ''

for symbol in text:
    if symbol.isdigit():
        result += '*'
    else:
        result += symbol

print(result)  # a*b*c*

# ------------------------------------------------------------
# 12. Цепочка замен
text = 'ABCCBA'
text = text.replace('A', '1')
text = text.replace('B', '2')
text = text.replace('C', '3')
print(text)  # 123321

# ------------------------------------------------------------
# 13. Многократная замена, пока шаблон встречается
text = '11112211'

while '11' in text:
    text = text.replace('11', '1')

print(text)

# Такой шаблон встречается в задачах с исполнителями строк.
# Важно понимать, что replace() без третьего аргумента
# заменяет сразу ВСЕ неперекрывающиеся вхождения.

# ------------------------------------------------------------
# 14. Если нужно заменить только первое вхождение
text = 'ABABAB'
text = text.replace('AB', 'X', 1)
print(text)  # XABAB

# ------------------------------------------------------------
# 15. Срезами можно заменить фрагмент вручную
text = 'abcdef'
i = 2
j = 4
text = text[:i] + 'XY' + text[j:]
print(text)  # abXYef

# ------------------------------------------------------------
# Частые ошибки

# 1. Ожидать, что replace(), lower(), upper(), strip() изменят строку сами.
#    Нужно сохранить результат: text = text.replace(...)
# 2. Забыть, что split() возвращает список строк.
# 3. Путать split() и join(): split разбивает, join соединяет.
# 4. В цикле while с заменами создать ситуацию, когда строка не меняется.
# 5. Не учитывать, что replace() по умолчанию заменяет все вхождения.

