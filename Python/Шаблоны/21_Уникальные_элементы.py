# Уникальные элементы

# Уникальность можно понимать по-разному:
# 1) убрать повторы и оставить по одному экземпляру каждого значения;
# 2) найти элементы, которые встретились ровно один раз.

# ------------------------------------------------------------
# 1. Удалить повторы через set()
numbers = [5, 2, 5, 7, 2, 9]
unique = set(numbers)
print(unique)

# ВАЖНО: множество не гарантирует сохранение исходного порядка.

# ------------------------------------------------------------
# 2. Получить обратно список
numbers = [5, 2, 5, 7, 2, 9]
unique = list(set(numbers))
print(unique)

# ------------------------------------------------------------
# 3. Удалить повторы с сохранением порядка
numbers = [5, 2, 5, 7, 2, 9]
result = []

for number in numbers:
    if number not in result:
        result.append(number)

print(result)  # [5, 2, 7, 9]

# ------------------------------------------------------------
# 4. Короткий современный способ с сохранением порядка
numbers = [5, 2, 5, 7, 2, 9]
result = list(dict.fromkeys(numbers))
print(result)  # [5, 2, 7, 9]

# ------------------------------------------------------------
# 5. Найти элементы, которые встретились ровно один раз
numbers = [5, 2, 5, 7, 2, 9]
result = []

for number in numbers:
    if numbers.count(number) == 1:
        result.append(number)

print(result)  # [7, 9]

# Этот способ понятный, но для больших списков не самый быстрый,
# потому что count() каждый раз снова просматривает список.

# ------------------------------------------------------------
# 6. Уникальные элементы через словарь частот
numbers = [5, 2, 5, 7, 2, 9]
frequency = {}

for number in numbers:
    frequency[number] = frequency.get(number, 0) + 1

result = []
for number in numbers:
    if frequency[number] == 1:
        result.append(number)

print(result)  # [7, 9]

# ------------------------------------------------------------
# 7. Количество различных значений
numbers = [5, 2, 5, 7, 2, 9]
print(len(set(numbers)))  # 4

# ------------------------------------------------------------
# 8. Проверить, есть ли повторы
numbers = [1, 2, 3, 4, 4]

if len(numbers) == len(set(numbers)):
    print('Все элементы различны')
else:
    print('Есть повторы')

# ------------------------------------------------------------
# 9. Общие элементы двух списков
first = [1, 2, 3, 4]
second = [3, 4, 5, 6]

common = set(first) & set(second)
print(common)  # {3, 4}

# ------------------------------------------------------------
# 10. Элементы, которые есть хотя бы в одном из списков
union = set(first) | set(second)
print(union)

# ------------------------------------------------------------
# 11. Элементы первого списка, которых нет во втором
difference = set(first) - set(second)
print(difference)  # {1, 2}

# ------------------------------------------------------------
# 12. Уникальные символы строки
text = 'информатика'
print(set(text))
print(len(set(text)))

# ------------------------------------------------------------
# Частые ошибки

# 1. Ожидать, что set() сохранит исходный порядок.
# 2. Путать «различные значения» и «значения, встретившиеся ровно один раз».
# 3. Использовать count() внутри цикла на очень больших данных.
# 4. Забыть преобразовать множество обратно в список, если нужен индекс или сортировка.
# 5. Пытаться положить в set изменяемые объекты вроде списков.

