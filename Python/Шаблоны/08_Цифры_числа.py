# Цифры числа

# С цифрами числа удобно работать двумя способами:
# 1) арифметически через % 10 и // 10;
# 2) как со строкой через str().

# ------------------------------------------------------------
# 1. Последняя цифра числа
n = 5837
last_digit = n % 10
print(last_digit)  # 7

# 2. Удалить последнюю цифру
n = 5837
n = n // 10
print(n)  # 583

# 3. Перебор цифр арифметически справа налево
n = 5837
while n > 0:
    digit = n % 10
    print(digit)
    n //= 10
# Будут получены: 7, 3, 8, 5

# 4. Сумма цифр
n = 5837
total = 0
while n > 0:
    total += n % 10
    n //= 10
print(total)  # 23

# 5. Количество цифр
n = 5837
count = 0
while n > 0:
    count += 1
    n //= 10
print(count)  # 4

# ВАЖНО: для n = 0 этот цикл не выполнится ни разу.
# Если ноль возможен, его нужно обработать отдельно.

# 6. Максимальная цифра
n = 5837
maximum = 0
while n > 0:
    digit = n % 10
    if digit > maximum:
        maximum = digit
    n //= 10
print(maximum)  # 8

# 7. Подсчёт цифр по условию
n = 583724
count = 0
while n > 0:
    digit = n % 10
    if digit % 2 == 0:
        count += 1
    n //= 10
print(count)  # 3

# 8. Построить число наоборот
n = 5837
reversed_number = 0
while n > 0:
    digit = n % 10
    reversed_number = reversed_number * 10 + digit
    n //= 10
print(reversed_number)  # 7385

# ------------------------------------------------------------
# 9. Работа с цифрами через строку
n = 5837
for digit in str(n):
    print(digit)
# Здесь digit — строка, а не число.

# 10. Сумма цифр через строку
n = 5837
total = 0
for digit in str(n):
    total += int(digit)
print(total)  # 23

# 11. Короткая сумма цифр
n = 5837
print(sum(map(int, str(n))))  # 23

# 12. Количество цифр через строку
n = 5837
print(len(str(n)))  # 4

# 13. Проверить наличие конкретной цифры
n = 5837
if '8' in str(n):
    print('Цифра 8 есть')

# 14. Количество конкретной цифры
n = 505150
print(str(n).count('5'))  # 2

# 15. Отрицательное число
n = -5837
# Для строкового способа знак '-' нужно убрать:
digits = str(abs(n))
print(sum(map(int, digits)))  # 23

# Для арифметического способа тоже удобно начать с abs(n).

# Частые ошибки:
# 1. Забыть, что % 10 берёт последнюю цифру.
# 2. Забыть n //= 10 внутри while и получить бесконечный цикл.
# 3. При строковом способе забыть int(digit), когда нужна арифметика.
# 4. Не обработать число 0 при арифметическом подсчёте количества цифр.
# 5. Не учесть знак минус у отрицательного числа.

