# Полный перебор

# Полный перебор — это проверка всех возможных вариантов.
# Он особенно полезен, когда количество вариантов небольшое
# или когда условие задачи прямо просит перебрать комбинации.

# ------------------------------------------------------------
# 1. Один параметр

for x in range(10):
    if x ** 2 == 49:
        print(x)  # 7

# ------------------------------------------------------------
# 2. Два параметра — два вложенных цикла

for x in range(10):
    for y in range(10):
        if x + y == 10 and x < y:
            print(x, y)

# ------------------------------------------------------------
# 3. Перебор нескольких значений из готового набора

values = [1, 2, 3]

for a in values:
    for b in values:
        print(a, b)

# Здесь допускаются одинаковые значения: 1 1, 2 2 и т.д.

# ------------------------------------------------------------
# 4. Если элементы должны быть различными

values = [1, 2, 3]

for a in values:
    for b in values:
        if a != b:
            print(a, b)

# ------------------------------------------------------------
# 5. Подсчитать количество подходящих вариантов

count = 0

for x in range(1, 10):
    for y in range(1, 10):
        if x * y % 5 == 0:
            count += 1

print(count)

# ------------------------------------------------------------
# 6. Найти максимум среди подходящих вариантов

maximum = None
best_x = None
best_y = None

for x in range(1, 20):
    for y in range(1, 20):
        if x + y <= 20:
            value = x * y

            if maximum is None or value > maximum:
                maximum = value
                best_x = x
                best_y = y

print(maximum, best_x, best_y)

# ------------------------------------------------------------
# 7. Перебор цифр числа фиксированной длины

count = 0

for a in range(1, 10):       # первая цифра не может быть 0
    for b in range(10):
        for c in range(10):
            number = 100 * a + 10 * b + c

            if number % 7 == 0:
                count += 1

print(count)

# ------------------------------------------------------------
# 8. Перебор булевых значений

for a in [False, True]:
    for b in [False, True]:
        result = (a or b) and not a
        print(a, b, result)

# Такой подход полезен для небольших логических задач.

# ------------------------------------------------------------
# 9. Перебор вариантов и досрочная остановка

found = False

for x in range(100):
    if x ** 2 == 81:
        print('Найдено:', x)
        found = True
        break

if not found:
    print('Решения нет')

