# 10. Когда полный перебор становится слишком большим

# Если каждый из 10 параметров принимает 10 значений,
# получаем 10 ** 10 вариантов — это уже слишком много.
# В таких задачах нужно искать более умный алгоритм:
# динамическое программирование, жадный подход,
# математические свойства и т.д.

# ------------------------------------------------------------
# Частые ошибки

# 1. Неправильно задать границы range().
# 2. Забыть, что правая граница range не включается.
# 3. Перебирать одинаковые значения, когда по условию они должны различаться.
# 4. Случайно посчитать одну и ту же пару дважды: (a, b) и (b, a).
# 5. Использовать полный перебор там, где число вариантов слишком велико.

