# Поиск подстрок

# Подстрока — фрагмент строки из одного или нескольких символов.
# В задачах часто нужно определить наличие, количество
# или позиции вхождений подстроки.

# ------------------------------------------------------------
# 1. Проверка наличия подстроки
text = 'информатика'

if 'форма' in text:
    print('Найдена')

# ------------------------------------------------------------
# 2. find() — позиция первого вхождения
text = 'ABCDABCD'
position = text.find('BCD')
print(position)  # 1

# Если подстроки нет, find() возвращает -1.
print(text.find('XYZ'))  # -1

# ------------------------------------------------------------
# 3. rfind() — позиция последнего вхождения
text = 'ABCDABCD'
print(text.rfind('BCD'))  # 5

# ------------------------------------------------------------
# 4. count() — количество НЕПЕРЕКРЫВАЮЩИХСЯ вхождений
text = 'ABABAB'
print(text.count('AB'))  # 3

# Важно: count() не всегда подходит,
# если вхождения могут перекрываться.

# ------------------------------------------------------------
# 5. Подсчёт вхождений вручную
text = 'ABABAB'
pattern = 'AB'
count = 0

for i in range(len(text) - len(pattern) + 1):
    if text[i:i + len(pattern)] == pattern:
        count += 1

print(count)  # 3

# ------------------------------------------------------------
# 6. Перекрывающиеся вхождения
text = 'AAAA'
pattern = 'AA'
count = 0

for i in range(len(text) - len(pattern) + 1):
    if text[i:i + len(pattern)] == pattern:
        count += 1

print(count)  # 3

# А text.count('AA') даст 2,
# потому что count() считает неперекрывающиеся вхождения.

# ------------------------------------------------------------
# 7. Получить все позиции подстроки
text = 'ABABAB'
pattern = 'AB'
positions = []

for i in range(len(text) - len(pattern) + 1):
    if text[i:i + len(pattern)] == pattern:
        positions.append(i)

print(positions)  # [0, 2, 4]

# ------------------------------------------------------------
# 8. Поиск следующего вхождения через find()
text = 'ABABAB'
pattern = 'AB'
position = text.find(pattern)

while position != -1:
    print(position)
    position = text.find(pattern, position + 1)

# position + 1 позволяет находить и перекрывающиеся вхождения.

# ------------------------------------------------------------
# 9. Подстрока между двумя маркерами
text = 'START_python_END'
left = text.find('START_')
right = text.find('_END')

if left != -1 and right != -1:
    fragment = text[left + len('START_'):right]
    print(fragment)  # python

# ------------------------------------------------------------
# 10. Частый шаблон для задания №24
# Проверяем фрагменты фиксированной длины.
text = 'AABABBAABB'
count = 0

for i in range(len(text) - 1):
    if text[i:i + 2] == 'AB':
        count += 1

print(count)

