# Частые ошибки

# 1. Забыть, что find() возвращает -1, если ничего не найдено.
# 2. Использовать count(), когда вхождения могут перекрываться.
# 3. Ошибиться в границе range(): нужна + 1.
# 4. Путать индекс начала подстроки и индекс её последнего символа.
# 5. Не учитывать длину pattern при взятии среза.

