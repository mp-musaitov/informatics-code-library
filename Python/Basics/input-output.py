# Ввод и вывод данных в Python

# Вывод текста
print('Привет, мир!')

# Ввод строки
name = input('Введите имя: ')
print('Привет,', name)

# Ввод целого числа
age = int(input('Введите возраст: '))
print('Ваш возраст:', age)

# Ввод нескольких целых чисел через пробел
a, b = map(int, input('Введите два числа через пробел: ').split())
print('Сумма:', a + b)