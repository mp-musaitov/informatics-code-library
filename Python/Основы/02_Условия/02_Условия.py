# Условный оператор в Python: if / elif / else

# 1. Простое условие
age = 18

if age >= 18:
    print('Совершеннолетний')

# 2. Условие с веткой else
number = 7

if number % 2 == 0:
    print('Чётное число')
else:
    print('Нечётное число')

# 3. Несколько вариантов через elif
score = 72

if score >= 90:
    print('Отлично')
elif score >= 70:
    print('Хорошо')
elif score >= 50:
    print('Удовлетворительно')
else:
    print('Нужно повторить тему')

# 4. Составные условия
x = 8

if x > 0 and x < 10:
    print('Число находится от 1 до 9')

# То же самое можно записать короче:
if 0 < x < 10:
    print('Число находится от 1 до 9')

# 5. Оператор or
weekday = 'суббота'

if weekday == 'суббота' or weekday == 'воскресенье':
    print('Выходной')
else:
    print('Будний день')

# 6. Оператор not
is_raining = False

if not is_raining:
    print('Можно идти гулять без зонта')

# 7. Проверка попадания в набор значений
answer = 'да'

if answer in ('да', 'yes', 'y'):
    print('Ответ положительный')

# Частые ошибки
# 1. Использовать = вместо ==.
# 2. Забыть двоеточие после условия.
# 3. Нарушить отступы.
# 4. Неправильно расположить условия: более строгие условия лучше проверять раньше.

