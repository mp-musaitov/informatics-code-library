# ОГЭ №16. Последовательность до завершающего нуля
#
# 0 является признаком окончания ввода
# и не входит в обрабатываемую последовательность.


# ============================================================
# БЛОК 1. КОЛИЧЕСТВО
# ============================================================
# Пример: посчитать количество чётных чисел.

count = 0

x = int(input())

while x != 0:
    if x % 2 == 0:
        count += 1

    x = int(input())

print(count)


# ============================================================
# БЛОК 2. КОЛИЧЕСТВО И СУММА
# ============================================================
# Пример: найти количество положительных чисел и их сумму.

count = 0
total = 0

x = int(input())

while x != 0:
    if x > 0:
        count += 1
        total += x

    x = int(input())

print(count)
print(total)


# ============================================================
# БЛОК 3. КОЛИЧЕСТВО И МАКСИМУМ
# ============================================================
# Пример: найти количество чисел, кратных 3,
# и максимальное среди них.

count = 0
maximum = None

x = int(input())

while x != 0:
    if x % 3 == 0:
        count += 1

        if maximum is None or x > maximum:
            maximum = x

    x = int(input())

print(count)
print(maximum)


# ============================================================
# БЛОК 4. КОЛИЧЕСТВО И МИНИМУМ
# ============================================================
# Пример: найти количество чисел, кратных 5,
# и минимальное среди них.

count = 0
minimum = None

x = int(input())

while x != 0:
    if x % 5 == 0:
        count += 1

        if minimum is None or x < minimum:
            minimum = x

    x = int(input())

print(count)
print(minimum)


