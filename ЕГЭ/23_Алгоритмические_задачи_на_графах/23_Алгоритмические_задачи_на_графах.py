print(int(dist[100]))


# ============================================================
# БЛОК 4. ВОССТАНОВЛЕНИЕ САМОГО КРАТКОГО ПУТИ
# ============================================================
# Если в задаче понадобится не только длина,
# но и сами вершины кратчайшего пути.

dist = {1: 0}
parent = {}
q = [(0, 1)]

while q:
    d, v = heappop(q)

    if d != dist[v]:
        continue

    for to, w in a.get(v, []):
        new_d = d + w

        if new_d < dist.get(to, float('inf')):
            dist[to] = new_d
            parent[to] = v
            heappush(q, (new_d, to))

v = 100
path = [v]

while v != 1:
    v = parent[v]
    path.append(v)

path.reverse()

print(path)
print(dist[100])


# ============================================================
# БЛОК 5. ТОПОЛОГИЧЕСКАЯ СОРТИРОВКА — АЛГОРИТМ КАНА
# ============================================================
# Нужна для задач на DAG: кратчайший/максимальный путь,
# количество путей и другие динамические алгоритмы.

from collections import deque

indegree = {}

for v in a:
    indegree.setdefault(v, 0)

    for to, w in a[v]:
        indegree[to] = indegree.get(to, 0) + 1

q = deque(
    v for v in indegree
    if indegree[v] == 0
)

order = []

while q:
    v = q.popleft()
    order.append(v)

    for to, w in a.get(v, []):
        indegree[to] -= 1

        if indegree[to] == 0:
            q.append(to)

print(order)


# ============================================================
# БЛОК 6. КРАТЧАЙШИЙ ПУТЬ В DAG
# ============================================================
dist_dag = {1: 0}

for v in order:
    if v not in dist_dag:
        continue

    for to, w in a.get(v, []):
        new_d = dist_dag[v] + w
        dist_dag[to] = min(
            dist_dag.get(to, float('inf')),
            new_d
        )

print(int(dist_dag[100]))


