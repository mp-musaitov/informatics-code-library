# ============================================================
from heapq import heappush, heappop

dist = {1: 0}
q = [(0, 1)]

while q:
    d, v = heappop(q)

    # В очереди могла остаться старая, более длинная запись.
    if d != dist[v]:
        continue

    for to, w in a.get(v, []):
        new_d = d + w

        if new_d < dist.get(to, float('inf')):
            dist[to] = new_d
            heappush(q, (new_d, to))

print(int(dist[100]))


