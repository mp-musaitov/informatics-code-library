# ============================================================
# БЛОК 2. ТО ЖЕ САМОЕ ЧЕРЕЗ ВЛОЖЕННЫЕ ЦИКЛЫ
# ============================================================
# Условие:
# Нужно построить нужную часть таблицы истинности без product().
#
# Этот вариант длиннее, но хорошо показывает сам принцип перебора.

print('x y z w')

for x in range(2):
    for y in range(2):
        for z in range(2):
            for w in range(2):
                f = ((not y) and x) or (y == z) or w

                if f == 0:
                    print(x, y, z, w)


# ============================================================
# БЛОК 3. ПОЛНАЯ ТАБЛИЦА ИСТИННОСТИ
# ============================================================
# Условие:
# Нужно увидеть все наборы значений и значение функции F.
#
# Полезно для проверки выражения или если в условии встречаются
# строки и с F = 0, и с F = 1.

print('x y z w F')

for x, y, z, w in product([0, 1], repeat=4):
    f = (x and not y) or (z == w)
    print(x, y, z, w, int(f))


# ============================================================
# БЛОК 4. АВТОМАТИЧЕСКОЕ ВОССТАНОВЛЕНИЕ ПОРЯДКА СТОЛБЦОВ
# ============================================================
# Условие:
# В таблице есть четыре неизвестных столбца и столбец F.
# Нужно автоматически определить порядок переменных.
#
# Этот способ полезен, если ручное сопоставление получилось запутанным.

rows = [
    # четыре неизвестных столбца и F
    (0, 1, 0, 1, 1),
    (1, 0, 0, 1, 0),
]

for p in permutations('xyzw'):
    ok = True

    for a, b, c, d, F in rows:
        values = dict(zip(p, (a, b, c, d)))

        x = values['x']
        y = values['y']
        z = values['z']
        w = values['w']

        # Заменить на функцию из конкретного задания
        f = (x and not y) or (z == w)

        if f != F:
            ok = False
            break

    if ok:
        print(*p)


# ============================================================
# БЛОК 5. ЕСЛИ В ТАБЛИЦЕ ЕСТЬ ПРОПУСКИ
# ============================================================
# Условие:
# Часть значений в строке неизвестна.
# Обозначаем неизвестные клетки None и перебираем вместо них 0 и 1.

row = [0, None, 1, None]
unknown = row.count(None)

for bits in product([0, 1], repeat=unknown):
    new_row = row[:]
    j = 0

    for i in range(len(new_row)):
        if new_row[i] is None:
            new_row[i] = bits[j]
            j += 1

    print(new_row)


