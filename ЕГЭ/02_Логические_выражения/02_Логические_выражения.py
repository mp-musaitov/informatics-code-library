# Основная задача: по фрагменту таблицы истинности определить
# порядок переменных в столбцах.
#
# На экзамене часто проще сначала вывести подходящие строки
# полной таблицы истинности, а затем сопоставить их с таблицей из условия.

from itertools import product, permutations


# ============================================================
# БЛОК 1. БЫСТРЫЙ ЭКЗАМЕНАЦИОННЫЙ СПОСОБ
# ============================================================
# Условие:
# Дана логическая функция и несколько строк таблицы истинности.
# Нужно определить порядок переменных в неизвестных столбцах.
#
# Идея:
# 1. Выводим только те строки полной таблицы истинности,
#    где F имеет нужное значение.
# 2. Сравниваем полученные строки с фрагментом таблицы из условия.
# 3. По совпадениям восстанавливаем порядок переменных.

print('x y z w')

for x, y, z, w in product([0, 1], repeat=4):
    f = ((not y) and x) or (y == z) or w

    # Если в строках условия F = 0:
    if f == 0:
        print(x, y, z, w)

