# ============================================================
# БЛОК 5. КОМАНДЫ С ПОДНЯТЫМ ХВОСТОМ
# ============================================================
# Условие:
# Черепаха строит одну фигуру, затем поднимает хвост,
# переходит в другую точку и строит вторую фигуру.
#
# При моделировании координат важно помнить:
# поднятый хвост НЕ отменяет движение,
# он только запрещает рисование линии.

x = 0
y = 0

# Первая фигура закончилась в текущей точке.
# Хвост поднят: переходим на 5 вправо и 3 вверх.
x += 5
y += 3

print(x, y)


# ============================================================
# БЛОК 6. БЫСТРЫЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# Если повороты только на 90 градусов,
# чаще всего достаточно такой модели.

x = 0
y = 0
d = 0

for _ in range(4):
    # Вперёд 6
    if d == 0:
        y += 6
    elif d == 1:
        x += 6
    elif d == 2:
        y -= 6
    else:
        x -= 6

    print(x, y)

    # Направо 90
    d = (d + 1) % 4


