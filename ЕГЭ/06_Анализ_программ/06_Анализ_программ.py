# ============================================================
# Основная идея:
# сначала понять геометрию движения,
# а уже потом считать целочисленные точки.
#
# Для простых квадратов и прямоугольников ручное решение
# обычно быстрее программы.


# ============================================================
# БЛОК 1. МОДЕЛИРОВАНИЕ ДВИЖЕНИЯ БЕЗ TURTLE
# ============================================================
# Условие:
# повороты только на 90 градусов.
# Нужно получить координаты вершин фигуры.
#
# Направления:
# 0 — вверх
# 1 — вправо
# 2 — вниз
# 3 — влево

x = 0
y = 0
direction = 0


def forward(n):
    global x, y

    if direction == 0:
        y += n
    elif direction == 1:
        x += n
    elif direction == 2:
        y -= n
    else:
        x -= n


def right():
    global direction
    direction = (direction + 1) % 4


def left():
    global direction
    direction = (direction - 1) % 4


# Пример: квадрат со стороной 6
print(x, y)

for _ in range(4):
    forward(6)
    print(x, y)
    right()


# ============================================================
# БЛОК 2. ПОДСЧЁТ ТОЧЕК В ПРЯМОУГОЛЬНИКЕ
# ============================================================
# Условие:
# известны координаты противоположных вершин прямоугольника.
# Стороны параллельны осям координат.

x1, y1 = 0, 0
x2, y2 = 6, 4

# Точки вместе с границей
with_border = (x2 - x1 + 1) * (y2 - y1 + 1)
print(with_border)

# Только точки строго внутри
inside = max(0, x2 - x1 - 1) * max(0, y2 - y1 - 1)
print(inside)


# ============================================================
# БЛОК 3. ПЕРЕСЕЧЕНИЕ ДВУХ ПРЯМОУГОЛЬНИКОВ
# ============================================================
# Условие:
# нужно найти целочисленные точки в общей части двух прямоугольников.

x1, x2, y1, y2 = 0, 8, 0, 6
x3, x4, y3, y4 = 3, 10, 2, 7

left_border = max(x1, x3)
right_border = min(x2, x4)
bottom_border = max(y1, y3)
top_border = min(y2, y4)

if left_border <= right_border and bottom_border <= top_border:
    points = (right_border - left_border + 1) * (top_border - bottom_border + 1)
else:
    points = 0

print(points)


