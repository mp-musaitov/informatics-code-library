# Python полезен для проверки готового набора и перебора кандидатов.


# ============================================================
# БЛОК 1. ПРОВЕРКА ПРЯМОГО УСЛОВИЯ ФАНО
# ============================================================
# Условие:
# Ни одно кодовое слово не должно быть началом другого.


def fano(codes):
    for i in range(len(codes)):
        for j in range(len(codes)):
            if i != j and codes[j].startswith(codes[i]):
                return False
    return True


codes = ['00', '01', '10', '11']
print(fano(codes))


# ============================================================
# БЛОК 2. ПРОВЕРКА НОВОГО КОДА
# ============================================================
# Условие:
# Есть известные кодовые слова.
# Нужно проверить, можно ли добавить новый код.

codes = ['00', '01', '10']
new_code = '11'

print(fano(codes + [new_code]))


# ============================================================
# БЛОК 3. ПОИСК ОДНОГО КРАТЧАЙШЕГО КОДА
# ============================================================
# Условие:
# Нужно найти новый код минимальной длины,
# который не нарушает прямое условие Фано.
#
# Сначала перебираем длину, потом все коды этой длины.

codes = ['00', '01', '10']

for length in range(1, 10):
    for n in range(2 ** length):
        new_code = bin(n)[2:].zfill(length)

        if new_code not in codes and fano(codes + [new_code]):
            print(new_code)
            raise SystemExit


# ============================================================
# БЛОК 4. ВЫВОД ВСЕХ КАНДИДАТОВ ДЛЯ НЕСКОЛЬКИХ НОВЫХ КОДОВ
# ============================================================
# Условие:
# Нужно подобрать несколько новых кодовых слов.
#
# Не всегда можно брать первый найденный код:
# он может закрыть ветвь дерева для следующего символа.
# Поэтому программа выводит кандидатов,
# а совместимый набор выбираем отдельно.

codes = ['1', '01']

for length in range(1, 6):
    print('Длина', length)

    for n in range(2 ** length):
        new_code = bin(n)[2:].zfill(length)

        if new_code not in codes and fano(codes + [new_code]):
            print(new_code)


# ============================================================
# БЛОК 5. ОБРАТНОЕ УСЛОВИЕ ФАНО
# ============================================================
# Условие:
# Ни одно кодовое слово не должно быть окончанием другого.


def reverse_fano(codes):
    for i in range(len(codes)):
        for j in range(len(codes)):
            if i != j and codes[j].endswith(codes[i]):
                return False
    return True


codes = ['00', '10', '11']
print(reverse_fano(codes))


# ============================================================
# БЛОК 6. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# Условие:
# Нужно быстро проверить набор кодов на прямое условие Фано.


def check(codes):
    for a in codes:
        for b in codes:
            if a != b and b.startswith(a):
                return False
    return True


print(check(['0', '10', '110', '111']))


