# БЛОК 6. ПОБИТОВАЯ КОНЪЮНКЦИЯ
# ============================================================
# Условие:
# В выражении используется побитовое И.
# В Python побитовое И — это оператор &.


def f(x, A):
    return ((x & A) == 0) or (x % 5 != 0)


for A in range(1000):
    if all(f(x, A) for x in range(1000)):
        print(A)
        break


