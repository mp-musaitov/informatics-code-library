# БЛОК 1. ДЕЛИМОСТЬ
# ============================================================
# Условие:
# Найти параметр A, при котором логическое выражение
# истинно для всех допустимых значений x.


def f(x, A):
    return (x % A == 0) or (x % 12 != 0)


for A in range(1, 100):
    if all(f(x, A) for x in range(1, 1000)):
        print(A)
        break


# ============================================================
# БЛОК 2. ДЕМОВЕРСИЯ ЕГЭ-2027
# ============================================================
# Условие:
# B = [70; 90]
# ДЕЛ(x, A) ∨ ((x ∈ B) → ¬ДЕЛ(x, 22))
# Найти наибольшее натуральное A.


def f(x, A):
    return (x % A == 0) or ((not (70 <= x <= 90)) or (x % 22 != 0))


for A in range(1000, 0, -1):
    if all(f(x, A) for x in range(1, 10000)):
        print(A)
        break


# ============================================================
# БЛОК 3. ДВЕ ПЕРЕМЕННЫЕ x И y
# ============================================================
# Условие:
# Найти A, при котором выражение истинно
# для всех натуральных x и y в достаточной области перебора.


def f(x, y, A):
    return (x + y <= 27) or (y <= x - 1) or (y >= A)


for A in range(1, 100):
    ok = True

    for x in range(1, 100):
        for y in range(1, 100):
            if not f(x, y, A):
                ok = False
                break

        if not ok:
            break

    if ok:
        print(A)
        break


