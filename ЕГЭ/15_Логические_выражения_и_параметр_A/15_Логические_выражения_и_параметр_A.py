# БЛОК 5. КОНЕЧНЫЕ МНОЖЕСТВА
# ============================================================
# Условие:
# x ∈ P → (¬(x ∈ Q) ∨ x ∈ A)
# Найти минимальное множество A.

P = {2, 4, 8, 12, 15}
Q = {3, 6, 8, 15}

A = set()

for x in P | Q:
    if (x in P) and (x in Q):
        A.add(x)

print(A)
print(len(A))


