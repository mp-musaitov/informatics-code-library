# БЛОК 1. НЕИЗВЕСТНАЯ ЦИФРА И ДЕЛИМОСТЬ
# ============================================================
# Условие:
# В нескольких числах одна и та же неизвестная цифра x.
# Нужно найти минимальное x, при котором сумма делится на 21.


def value(digits, base):
    n = 0
    for digit in digits:
        n = n * base + digit
    return n


base = 22

for x in range(base):
    a = value([2, 7, x, 9, 8, 8, 7, 6], base)
    b = value([2, 6, x, 5, 1], base)
    c = value([7, 1, 1, x, 5], base)

    s = a + b + c

    if s % 21 == 0:
        print(x, s // 21)
        break


