# БЛОК 4. ПЕРЕБОР x ПО КОЛИЧЕСТВУ НУЛЕЙ
# ============================================================
# Условие:
# Найти наибольшее x <= 2030,
# при котором в семеричной записи выражения
# 7^170 + 7^100 - x содержится ровно 71 нуль.

for x in range(2030, 0, -1):
    n = 7**170 + 7**100 - x
    count = 0

    while n > 0:
        if n % 7 == 0:
            count += 1
        n //= 7

    if count == 71:
        print(x)
        break


