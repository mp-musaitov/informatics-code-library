# ЕГЭ №19. Теория игр — первый ход

# ============================================================
# БЛОК 1. ВСЕ ВОЗМОЖНЫЕ ХОДЫ
# ============================================================
def moves(x, y):
    return ((x + 4, y), (x, y + 4), (x * 2, y), (x, y * 2))

# ============================================================
# БЛОК 2. ПОБЕДНАЯ ПОЗИЦИЯ
# ============================================================
def win(x, y):
    return x + y >= 133

# ============================================================
# БЛОК 3. МОЖНО ЛИ ВЫИГРАТЬ ЗА ОДИН ХОД
# ============================================================
def can_win_one_move(x, y):
    return any(win(*p) for p in moves(x, y))

# ============================================================
# БЛОК 4. №19 — НАГЛЯДНЫЙ ПЕРЕБОР
# ============================================================
for S in range(1, 116):
    ok = False
    for p in moves(17, S):
        if win(*p):
            continue
        for v in moves(*p):
            if win(*v):
                ok = True
                break
        if ok:
            break
    if ok:
        print(S)
        break

# ============================================================
# БЛОК 5. ТО ЖЕ ЧЕРЕЗ any()
# ============================================================
for S in range(1, 116):
    ok = any(
        not win(*p) and any(win(*v) for v in moves(*p))
        for p in moves(17, S)
    )
    if ok:
        print(S)
        break

# ============================================================
# БЛОК 6. ПОЧЕМУ ОТВЕТ 29
# ============================================================
# (17, 29) -> Петя удваивает вторую кучу -> (17, 58)
# 17 + 58 = 75 < 133, игра продолжается.
# Ваня удваивает вторую кучу -> (17, 116)
# 17 + 116 = 133, Ваня выигрывает первым ходом.

S = 29
after_petya = (17, S * 2)
after_vanya = (17, after_petya[1] * 2)
print(after_petya)
print(after_vanya)
print(sum(after_vanya))

# ============================================================
# БЛОК 7. УНИВЕРСАЛЬНЫЙ ШАБЛОН ДЛЯ №19
# ============================================================
# Меняем начальную позицию, диапазон S, moves() и win().

for S in range(1, 116):
    possible = False
    for first_move in moves(17, S):
        if win(*first_move):
            continue
        if any(win(*second_move) for second_move in moves(*first_move)):
            possible = True
            break
    if possible:
        print(S)
        break

