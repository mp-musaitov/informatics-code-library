# ============================================================
# БЛОК 1. СКОЛЬКО БИТ НУЖНО НА ОДИН СИМВОЛ
# ============================================================
# Условие:
# Алфавит содержит N символов.
# Найти минимальное количество бит на один символ.

N = 26

i = 0
while 2 ** i < N:
    i += 1

print(i)


# ============================================================
# БЛОК 2. ПАМЯТЬ НА ОДИН ПАРОЛЬ
# ============================================================
# Условие:
# Известны мощность алфавита N и длина пароля L.
# Найти минимальное целое число байт на один пароль.

N = 26
L = 15

i = 0
while 2 ** i < N:
    i += 1

bits = L * i
bytes_per_item = (bits + 7) // 8

print(bytes_per_item)


# ============================================================
# БЛОК 3. ОБЩИЙ ОБЪЁМ ПАМЯТИ
# ============================================================
# Условие:
# Известны алфавит, длина записи и количество записей.
# Найти общий объём памяти.

N = 12
L = 20
K = 1000

i = 0
while 2 ** i < N:
    i += 1

bytes_per_item = (L * i + 7) // 8
total = bytes_per_item * K

print(bytes_per_item)
print(total)


# ============================================================
# БЛОК 4. МАКСИМАЛЬНАЯ МОЩНОСТЬ АЛФАВИТА
# ============================================================
# Условие:
# Известны длина номера L, количество номеров K
# и максимальный общий объём V.
# Найти максимальную мощность алфавита.
# Пример соответствует формату демоверсии ЕГЭ-2027.

L = 157
K = 12450
V = 955 * 1024

bytes_per_item = V // K

i = 0
while L * (i + 1) <= 8 * bytes_per_item:
    i += 1

N = 2 ** i

print(bytes_per_item)
print(i)
print(N)


# ============================================================
# БЛОК 5. МАКСИМАЛЬНАЯ МОЩНОСТЬ АЛФАВИТА ПЕРЕБОРОМ
# ============================================================
# Условие:
# Тот же тип задачи, но решаем перебором.
# Удобно как проверка решения.

L = 157
K = 12450
V = 955 * 1024

answer = 0

for N in range(1, 1000):
    i = 0

    while 2 ** i < N:
        i += 1

    bytes_per_item = (L * i + 7) // 8

    if bytes_per_item * K <= V:
        answer = N

print(answer)


# ============================================================
# БЛОК 6. МАКСИМАЛЬНАЯ ДЛИНА ПАРОЛЯ
# ============================================================
# Условие:
# Известны мощность алфавита N и память M байт
# на один пароль. Найти максимальную длину пароля.

N = 26
M = 20

i = 0
while 2 ** i < N:
    i += 1

L = 8 * M // i

print(L)


# ============================================================
# БЛОК 7. ДОПОЛНИТЕЛЬНАЯ ИНФОРМАЦИЯ
# ============================================================
# Условие:
# На всю запись выделено M байт.
# Часть памяти занимает пароль.
# Найти объём дополнительной информации.

N = 26
L = 15
M = 40

i = 0
while 2 ** i < N:
    i += 1

password_bytes = (L * i + 7) // 8
extra_bytes = M - password_bytes

print(password_bytes)
print(extra_bytes)


# ============================================================
# БЛОК 8. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# Основная цепочка:
# N -> i -> L * i бит -> целое число байт -> общий объём.

N = 26
L = 15
K = 1000

i = 0
while 2 ** i < N:
    i += 1

M = (L * i + 7) // 8

print(M * K)


# ============================================================
# БЫСТРАЯ ПАМЯТКА
# ============================================================
# N — мощность алфавита
# i — бит на символ
# L — длина записи
# M — байт на одну запись
# K — количество записей
#
# Минимальное i:
# 2 ** i >= N
#
# Бит на одну запись:
# L * i
#
# Целое число байт:
# (L * i + 7) // 8
#
# Общий объём:
# M * K
#
# Если ищем максимальный алфавит:
# N = 2 ** i
#
# 1 Кбайт = 1024 байта
# 1 Мбайт = 1024 Кбайт
