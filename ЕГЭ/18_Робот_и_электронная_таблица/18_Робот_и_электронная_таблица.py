# БЛОК 1. МАКСИМАЛЬНАЯ СУММА БЕЗ СТЕН
# ============================================================
a = [[1, 8, 4], [3, 2, 5], [7, 1, 6]]
n, m = len(a), len(a[0])
dp = [[0] * m for _ in range(n)]
dp[0][0] = a[0][0]
for j in range(1, m):
    dp[0][j] = dp[0][j - 1] + a[0][j]
for i in range(1, n):
    dp[i][0] = dp[i - 1][0] + a[i][0]
for i in range(1, n):
    for j in range(1, m):
        dp[i][j] = a[i][j] + max(dp[i - 1][j], dp[i][j - 1])
print(dp[-1][-1])

