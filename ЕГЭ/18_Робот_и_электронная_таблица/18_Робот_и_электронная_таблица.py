# БЛОК 7. УНИВЕРСАЛЬНЫЙ ШАГ С УЧЁТОМ ДОСТУПНЫХ ПУТЕЙ
# ============================================================
def next_value(cell, from_top, from_left, mode='max'):
    ways = []
    if from_top is not None:
        ways.append(from_top)
    if from_left is not None:
        ways.append(from_left)
    if not ways:
        return None
    if mode == 'max':
        return cell + max(ways)
    return cell + min(ways)

print(next_value(5, 13, 11, 'max'))
print(next_value(5, 13, 11, 'min'))

