# ============================================================
# БЛОК 1. ОТБОР ПО НУЖНЫМ ID
# ============================================================
# Условие:
# Из справочников уже известны ID нужных товаров и магазинов.
# Нужно найти сумму количества по подходящим строкам.

needed_products = {101, 105, 120}
needed_shops = {3, 8, 15}

records = [
    (101, 3, 20),
    (105, 8, 15),
    (120, 4, 10),
    (101, 15, 7),
]

answer = 0

for product_id, shop_id, amount in records:
    if product_id in needed_products and shop_id in needed_shops:
        answer += amount

print(answer)


# ============================================================
# БЛОК 2. СПРАВОЧНИКИ ЧЕРЕЗ СЛОВАРИ
# ============================================================
# Условие:
# Есть отдельные справочники товаров и магазинов.
# Нужно определить свойства по ID и проверить условие.

products = {
    101: 'Напитки',
    102: 'Хлеб',
    103: 'Молочные продукты',
}

shops = {
    1: 'Центральный',
    2: 'Северный',
    3: 'Центральный',
}

records = [
    (101, 1, 12),
    (102, 1, 5),
    (101, 2, 8),
    (103, 3, 10),
]

answer = 0

for product_id, shop_id, amount in records:
    if products[product_id] == 'Напитки' and shops[shop_id] == 'Центральный':
        answer += amount

print(answer)


# ============================================================
# БЛОК 3. КОЛИЧЕСТВО СТРОК, А НЕ СУММА ЗНАЧЕНИЙ
# ============================================================
# Условие:
# Нужно определить, сколько записей удовлетворяет условию.

count = 0

for product_id, shop_id, amount in records:
    if products[product_id] == 'Напитки':
        count += 1

print(count)


# ============================================================
# БЛОК 4. СТОИМОСТЬ = ЦЕНА * КОЛИЧЕСТВО
# ============================================================
# Условие:
# Для каждой подходящей записи нужно посчитать стоимость,
# а затем найти общую сумму.

prices = {
    101: 120,
    102: 60,
    103: 90,
}

answer = 0

for product_id, shop_id, amount in records:
    if shops[shop_id] == 'Центральный':
        answer += prices[product_id] * amount

print(answer)


# ============================================================
# БЛОК 5. ОСТАТОК = ПОСТУПЛЕНИЕ - ПРОДАЖА
# ============================================================
# Условие:
# Нужно найти остаток товара по операциям.
# Положительное значение — поступление,
# отрицательное — продажа.

operations = [
    (101, 50),
    (101, -20),
    (102, 30),
    (101, -10),
]

balance = 0

for product_id, amount in operations:
    if product_id == 101:
        balance += amount

print(balance)


