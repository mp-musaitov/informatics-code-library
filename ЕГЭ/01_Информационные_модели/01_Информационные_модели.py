from itertools import permutations


# ============================================================
# БЛОК 1. БЫСТРЫЙ ЭКЗАМЕНАЦИОННЫЙ ПЕРЕБОР
# ============================================================
# Условие:
# Вершины графа обозначены буквами, а в таблице — номерами.
# Нужно определить, какая буква соответствует каждому номеру.
#
# tab — соседи каждой вершины таблицы.
# Например, строка '24' означает, что вершина 1
# соединена с вершинами 2 и 4.
#
# pic — рёбра графа с рисунка.
# Например, 'аб' означает, что вершины а и б соединены.
#
# Этот вариант особенно удобен на экзамене:
# код короткий и быстро набирается вручную.


tab = '24 146 56 1267 36 23457 46'.split()
pic = 'аб ав бв вд вг ве де ге гк ек'.split()

for var in permutations('абвгдек'):
    if all(str(var.index(x) + 1) in tab[var.index(y)] for x, y in pic):
        print(*var)

# Если программа вывела, например:
# а г б в д е к
# это означает:
# 1 -> а
# 2 -> г
# 3 -> б
# 4 -> в
# 5 -> д
# 6 -> е
# 7 -> к


# ============================================================
# БЛОК 2. СТЕПЕНИ ВЕРШИН
# ============================================================
# Условие:
# Дан граф. Нужно посмотреть, сколько соседей у каждой вершины.
# Это помогает начать сопоставление графа с таблицей вручную.


graph = {
    'A': ['B', 'C', 'D'],
    'B': ['A', 'D'],
    'C': ['A', 'D'],
    'D': ['A', 'B', 'C']
}

for v in graph:
    print(v, len(graph[v]))


# ============================================================
# БЛОК 3. УНИВЕРСАЛЬНАЯ ПРОВЕРКА ГРАФА
# ============================================================
# Условие:
# Вершины графа обозначены буквами, а в таблице — номерами.
# Нужно определить точное соответствие.
#
# В отличие от быстрого шаблона выше,
# здесь явно сравнивается весь набор рёбер графа и таблицы.
# Такой вариант длиннее, но универсальнее и нагляднее.


letters = ['A', 'B', 'C', 'D']
numbers = [1, 2, 3, 4]

# Рёбра графа из рисунка
edges_graph = {
    frozenset(('A', 'B')),
    frozenset(('A', 'C')),
    frozenset(('B', 'D')),
    frozenset(('C', 'D'))
}

# Связи из таблицы
edges_table = {
    frozenset((1, 2)),
    frozenset((1, 4)),
    frozenset((2, 3)),
    frozenset((3, 4))
}

for p in permutations(numbers):
    d = dict(zip(letters, p))

    converted = set()

    for edge in edges_graph:
        a, b = edge
        converted.add(frozenset((d[a], d[b])))

    if converted == edges_table:
        print(d)


# ============================================================
# БЛОК 4. ЕСЛИ В ТАБЛИЦЕ УКАЗАНЫ ДЛИНЫ ДОРОГ
# ============================================================
# Условие:
# После определения соответствия нужно найти длину дороги
# между двумя заданными вершинами, например A и D.
#
# В таблице удобно хранить длины дорог в словаре.


roads = {
    frozenset((1, 2)): 12,
    frozenset((1, 4)): 17,
    frozenset((2, 3)): 25,
    frozenset((3, 4)): 9
}

# Допустим, после сопоставления получили:
correspondence = {
    'A': 1,
    'B': 2,
    'C': 4,
    'D': 3
}

x = correspondence['A']
y = correspondence['D']

print(roads[frozenset((x, y))])


