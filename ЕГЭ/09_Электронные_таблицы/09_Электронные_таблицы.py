# ============================================================
# БЛОК 1. ВСЕ ЧИСЛА В СТРОКЕ РАЗЛИЧНЫ
# ============================================================
# Условие:
# Проверить, что в строке нет повторяющихся чисел.

s = [10, 20, 30, 40, 50]

if len(s) == len(set(s)):
    print('Все числа различны')


# ============================================================
# БЛОК 2. МАКСИМУМ, МИНИМУМ И СУММА ОСТАЛЬНЫХ
# ============================================================
# Условие:
# Удвоенная сумма максимального и минимального числа
# больше суммы остальных чисел.

s = [10, 20, 30, 40, 50]

if 2 * (max(s) + min(s)) > sum(s) - max(s) - min(s):
    print('Условие выполнено')


# ============================================================
# БЛОК 3. ДЕМО-2027: ДВА УСЛОВИЯ ОДНОВРЕМЕННО
# ============================================================
# Условие:
# 1) все пять чисел различны;
# 2) удвоенная сумма максимального и минимального
#    больше суммы остальных трёх.

s = [12, 25, 31, 48, 70]

if len(s) == len(set(s)) and 2 * (max(s) + min(s)) > sum(s) - max(s) - min(s):
    print('Строка подходит')


# ============================================================
# БЛОК 4. КОЛИЧЕСТВО ЧЁТНЫХ ЧИСЕЛ
# ============================================================
# Условие:
# Посчитать, сколько чисел в строке являются чётными.

s = [12, 25, 30, 41, 56]

k = 0
for x in s:
    if x % 2 == 0:
        k += 1

print(k)


# ============================================================
# БЛОК 5. РОВНО ТРИ ЧЁТНЫХ ЧИСЛА
# ============================================================
# Условие:
# В строке должно быть ровно три чётных числа.

s = [12, 25, 30, 41, 56]

if sum(x % 2 == 0 for x in s) == 3:
    print('Ровно три чётных')


# ============================================================
# БЛОК 6. ЧИСЛА ИДУТ ПО ВОЗРАСТАНИЮ
# ============================================================
# Условие:
# Каждый следующий элемент строго больше предыдущего.

s = [10, 20, 30, 40, 50]

if all(s[i] < s[i + 1] for i in range(len(s) - 1)):
    print('Строго возрастают')


# ============================================================
# БЛОК 7. КОЛИЧЕСТВО ЧИСЕЛ ПО УСЛОВИЮ
# ============================================================
# Условие:
# Например, ровно три числа должны быть больше 50.

s = [20, 55, 61, 40, 73]

if sum(x > 50 for x in s) == 3:
    print('Подходит')


# ============================================================
# БЛОК 8. ОДНА ПАРА ОДИНАКОВЫХ ЧИСЕЛ
# ============================================================
# Условие:
# Одно значение встречается ровно два раза,
# остальные значения встречаются по одному разу.

s = [10, 20, 20, 30, 40]

counts = [s.count(x) for x in s]

if counts.count(2) == 2 and counts.count(1) == len(s) - 2:
    print('Ровно одна пара')


# ============================================================
# БЛОК 9. ЧТЕНИЕ СТРОК ИЗ ТЕКСТОВОГО ФАЙЛА
# ============================================================
# Условие:
# Файл предварительно сохранён в текстовом формате,
# в каждой строке числа разделены пробелами.

count = 0

with open('9.txt') as f:
    for line in f:
        s = list(map(int, line.split()))

        if len(s) == len(set(s)) and 2 * (max(s) + min(s)) > sum(s) - max(s) - min(s):
            count += 1

print(count)


# ============================================================
# БЛОК 10. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# Подставляем нужное условие внутрь if.

count = 0

with open('9.txt') as f:
    for line in f:
        s = list(map(int, line.split()))

        if len(s) == len(set(s)):
            count += 1

print(count)


# ============================================================
# ПАМЯТКА
# ============================================================
# len(s) == len(set(s))  -> все числа различны
# max(s)                 -> максимум
# min(s)                 -> минимум
# sum(s)                 -> сумма
# s.count(x)             -> сколько раз встречается x
# x % 2 == 0             -> x чётное
# sum(условие for x in s)-> сколько элементов удовлетворяют условию
#
# Важно:
# обычный open() не читает .xlsx и .ods как числовые строки.
