# ============================================================
# БЛОК 1. ИНВЕРСИЯ БИТОВ
# ============================================================
# Условие:
# Машина заменяет 0 на 1, а 1 на 0.
# Нужно получить результат преобразования строки.

s = '001011'
result = ''

for x in s:
    if x == '0':
        result += '1'
    else:
        result += '0'

print(result)


# ============================================================
# БЛОК 2. ПОДСЧЁТ НУЛЕЙ И ЕДИНИЦ
# ============================================================
# Условие:
# После анализа таблицы нужно узнать,
# сколько в последовательности нулей и единиц.

s = '001011'

print(s.count('0'))
print(s.count('1'))


# ============================================================
# БЛОК 3. КОЛИЧЕСТВО СИМВОЛОВ ПОСЛЕ ИНВЕРСИИ
# ============================================================
# Условие:
# Машина полностью инвертирует двоичную строку.
# Если было x нулей и y единиц,
# после инверсии станет y нулей и x единиц.

zeros = 120
ones = 80

new_zeros = ones
new_ones = zeros

print(new_zeros, new_ones)


# ============================================================
# БЛОК 4. НЕСКОЛЬКО ЭТАПОВ ПРЕОБРАЗОВАНИЯ
# ============================================================
# Условие:
# Сначала машина инвертирует все биты,
# затем ещё один 0 превращает в 1.

zeros = 120
ones = 80

new_zeros = ones - 1
new_ones = zeros + 1

print(new_zeros, new_ones)


# ============================================================
# БЛОК 5. ВОССТАНОВЛЕНИЕ ИСХОДНОГО КОЛИЧЕСТВА
# ============================================================
# Условие:
# После работы машины число нулей равно
# исходному числу единиц минус 1.
# Известно, что после работы осталось 125 нулей.

final_zeros = 125
initial_ones = final_zeros + 1

print(initial_ones)


# ============================================================
# БЛОК 6. ПЕРЕВОД ИЗ ДЕСЯТИЧНОЙ СИСТЕМЫ В ДВОИЧНУЮ
# ============================================================
# Условие:
# Последовательность на ленте является двоичной записью числа.

n = 240
s = bin(n)[2:]

print(s)


# ============================================================
# БЛОК 7. ПЕРЕВОД ИЗ ДВОИЧНОЙ СИСТЕМЫ В ДЕСЯТИЧНУЮ
# ============================================================
# Условие:
# После работы машины получена двоичная строка.
# Нужно определить значение числа.

s = '11110000'
print(int(s, 2))


# ============================================================
# БЛОК 8. БЫСТРАЯ ПРОВЕРКА ИНВЕРСИИ
# ============================================================
# Условие:
# Нужно быстро получить строку с противоположными битами.

s = '001011'
result = ''.join('1' if x == '0' else '0' for x in s)

print(result)


# ============================================================
# БЛОК 9. УПРОЩЁННЫЙ СИМУЛЯТОР ОДНОГО СОСТОЯНИЯ
# ============================================================
# Условие:
# Для проверки идеи машина идёт справа налево
# и инвертирует все биты.
# Это НЕ универсальный симулятор машины Тьюринга,
# а только проверка конкретного поведения.

s = list('001011')
head = len(s) - 1

while head >= 0:
    if s[head] == '0':
        s[head] = '1'
    else:
        s[head] = '0'

    head -= 1

print(''.join(s))


# ============================================================
# БЛОК 10. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# 1. Сначала читаем таблицу переходов и формулируем,
#    что делает машина словами.
# 2. Затем считаем только то, что требуется в вопросе.
# 3. Python используем для проверки или простых вычислений.

s = '001011'

print(s.count('0'))
print(s.count('1'))


