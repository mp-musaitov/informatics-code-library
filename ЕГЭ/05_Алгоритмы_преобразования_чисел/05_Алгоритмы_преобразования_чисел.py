# ЕГЭ №5. Алгоритмы преобразования чисел
#
# Основная идея:
# 1. Перебираем N.
# 2. Переводим его в двоичную запись.
# 3. Выполняем алгоритм из условия.
# 4. Получаем R.
# 5. Проверяем условие.


# ============================================================
# БЛОК 1. БАЗОВЫЙ ШАБЛОН
# ============================================================
# Условие:
# Дан алгоритм преобразования числа N.
# Нужно найти подходящее N или R.

for n in range(1, 1000):
    s = bin(n)[2:]

    # Здесь действия из условия
    s += '01'

    r = int(s, 2)

    if r > 100:
        print(n, r)
        break


# ============================================================
# БЛОК 2. ДОПИСЫВАНИЕ БИТОВ ПО ЧЁТНОСТИ N
# ============================================================
# Условие:
# Если N чётное, справа дописывается 0,
# если нечётное — 1.

for n in range(1, 1000):
    s = bin(n)[2:]

    if n % 2 == 0:
        s += '0'
    else:
        s += '1'

    r = int(s, 2)

    if r > 100:
        print(n, r)
        break


# ============================================================
# БЛОК 3. ДОПИСЫВАНИЕ ПО КОЛИЧЕСТВУ ЕДИНИЦ
# ============================================================
# Условие:
# Если количество единиц в двоичной записи чётное,
# дописывается 0, иначе — 1.

for n in range(1, 1000):
    s = bin(n)[2:]

    if s.count('1') % 2 == 0:
        s += '0'
    else:
        s += '1'

    r = int(s, 2)

    if r > 100:
        print(n, r)
        break


# ============================================================
# БЛОК 4. ПОВТОРЕНИЕ ОДНОГО ПРАВИЛА НЕСКОЛЬКО РАЗ
# ============================================================
# Условие:
# Правило выполняется два раза подряд.
# Каждый следующий шаг выполняется уже над изменённой строкой.

for n in range(1, 1000):
    s = bin(n)[2:]

    for _ in range(2):
        if s.count('1') % 2 == 0:
            s += '0'
        else:
            s += '1'

    r = int(s, 2)

    if r > 100:
        print(n, r)
        break


# ============================================================
# БЛОК 5. ДОПИСЫВАНИЕ ОСТАТКА ОТ ДЕЛЕНИЯ
# ============================================================
# Условие:
# К двоичной записи дописывается остаток от деления
# исходного числа N на 2.

for n in range(1, 1000):
    s = bin(n)[2:]

    s += str(n % 2)

    r = int(s, 2)

    if r > 100:
        print(n, r)
        break


# ============================================================
# БЛОК 6. ЗАМЕНА И ПЕРЕСТАНОВКА РАЗРЯДОВ
# ============================================================
# Условие:
# Нужно изменить двоичную запись числа с помощью срезов.
# Например, поменять местами первый и последний символы.

for n in range(2, 1000):
    s = bin(n)[2:]

    s = s[-1] + s[1:-1] + s[0]

    r = int(s, 2)

    if r > 100:
        print(n, r)
        break


# ============================================================
# БЛОК 7. ПОИСК МИНИМАЛЬНОГО N
# ============================================================
# Условие:
# Нужно найти наименьшее N, для которого R удовлетворяет условию.
#
# Перебираем N по возрастанию и после первого ответа делаем break.

for n in range(1, 10000):
    s = bin(n)[2:]
    s += '01'
    r = int(s, 2)

    if r > 500:
        print(n)
        break


# ============================================================
# БЛОК 8. ПОИСК МИНИМАЛЬНОГО R
# ============================================================
# Условие:
# Нужно найти не минимальное N, а минимальное значение R.
#
# Это не одно и то же. Собираем подходящие R и берём минимум.

answers = []

for n in range(1, 10000):
    s = bin(n)[2:]
    s += '01'
    r = int(s, 2)

    if r > 500:
        answers.append(r)

print(min(answers))


# ============================================================
# БЛОК 9. ПОИСК МАКСИМАЛЬНОГО N
# ============================================================
# Условие:
# Нужно найти наибольшее N, удовлетворяющее условию.
#
# Сохраняем последнее подходящее значение.

answer = None

for n in range(1, 10000):
    s = bin(n)[2:]
    s += '01'
    r = int(s, 2)

    if r < 500:
        answer = n

print(answer)


# ============================================================
# БЛОК 10. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# Условие:
# Нужно быстро переписать алгоритм из задания и найти первый ответ.

for n in range(1, 10000):
    s = bin(n)[2:]

    # алгоритм из условия
    if s.count('1') % 2 == 0:
        s += '0'
    else:
        s += '1'

    r = int(s, 2)

    if r > 100:
        print(n)
        break


# ============================================================
# ПАМЯТКА
# ============================================================
# bin(n)[2:]      -> двоичная запись без 0b
# int(s, 2)       -> перевод двоичной строки в число
# s += '0'        -> дописать 0 справа
# s = '1' + s     -> дописать 1 слева
# s.count('1')    -> количество единиц
# n % 2           -> чётность числа
#
# Важно:
# минимальное N и минимальное R — разные вопросы.
# Если ищется минимальное N, обычно подходит break после первого ответа.
