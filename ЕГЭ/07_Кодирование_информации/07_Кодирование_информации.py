# ============================================================
# БЛОК 6. ОБЪЁМ ЗВУКОВОГО ФАЙЛА
# ============================================================
# Условие:
# Известны частота дискретизации, глубина кодирования,
# длительность и количество каналов.

frequency = 12000
bit_depth = 16
seconds = 3 * 60 + 10
channels = 2

bits = frequency * bit_depth * seconds * channels
kbytes = bits / 8 / 1024
mbytes = bits / 8 / 1024**2

print(kbytes, 'Кбайт')
print(mbytes, 'Мбайт')


# ============================================================
# БЛОК 7. СЖАТИЕ ФАЙЛА НА p ПРОЦЕНТОВ
# ============================================================
# Условие:
# Файл уменьшился на p процентов.

old_size = 500
p = 25

new_size = old_size * (100 - p) / 100

print(new_size)


# ============================================================
# БЛОК 8. ВОССТАНОВЛЕНИЕ РАЗМЕРА ДО СЖАТИЯ
# ============================================================
# Условие:
# Известен размер после сжатия и процент уменьшения.

new_size = 375
p = 25

old_size = new_size / ((100 - p) / 100)

print(old_size)


