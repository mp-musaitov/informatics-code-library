# ============================================================
# БЛОК 1. ОБЪЁМ РАСТРОВОГО ИЗОБРАЖЕНИЯ
# ============================================================
# Условие:
# Изображение W × H пикселей, глубина цвета depth бит.
# Найти объём изображения.

w = 800
h = 600
depth = 16

bits = w * h * depth
bytes_ = bits / 8
kbytes = bits / 8 / 1024
mbytes = bits / 8 / 1024**2

print(bits, 'бит')
print(bytes_, 'байт')
print(kbytes, 'Кбайт')
print(mbytes, 'Мбайт')


# ============================================================
# БЛОК 2. МИНИМАЛЬНАЯ ГЛУБИНА ЦВЕТА
# ============================================================
# Условие:
# Известно количество цветов.
# Найти минимальное число бит на один пиксель.

colors = 100

depth = 0

while 2 ** depth < colors:
    depth += 1

print(depth)


# ============================================================
# БЛОК 3. МАКСИМАЛЬНОЕ КОЛИЧЕСТВО ЦВЕТОВ
# ============================================================
# Условие:
# Известен максимальный объём изображения.
# Найти максимальную глубину цвета и число цветов.

w = 1024
h = 768
max_kbytes = 600

max_bits = max_kbytes * 1024 * 8

depth = int(max_bits // (w * h))
colors = 2 ** depth

print(depth, 'бит на пиксель')
print(colors, 'цветов')


