# ============================================================
# БЛОК 1. НАЙТИ АДРЕС СЕТИ ЧЕРЕЗ ipaddress
# ============================================================
# Условие:
# Дан IP-адрес узла и маска. Нужно найти адрес сети.

from ipaddress import ip_network

net = ip_network('192.168.159.86/255.255.252.0', strict=False)
print(net.network_address)


# ============================================================
# БЛОК 2. СУММА ОКТЕТОВ АДРЕСА СЕТИ
# ============================================================
# Условие:
# После нахождения адреса сети нужно сложить его октеты.

net = ip_network('192.168.159.86/255.255.252.0', strict=False)
address = str(net.network_address)
print(sum(map(int, address.split('.'))))


# ============================================================
# БЛОК 3. АДРЕС СЕТИ БЕЗ ipaddress
# ============================================================
# Условие:
# Найти адрес сети вручную через побитовое И.

ip = [192, 168, 159, 86]
mask = [255, 255, 252, 0]

network = []
for i in range(4):
    network.append(ip[i] & mask[i])

print(network)
print(sum(network))


# ============================================================
# БЛОК 4. ДЛИНА ПРЕФИКСА И КОЛИЧЕСТВО АДРЕСОВ
# ============================================================
# Условие:
# По IP и маске определить длину префикса и число адресов сети.

net = ip_network('192.168.159.86/255.255.252.0', strict=False)

print(net.prefixlen)
print(net.num_addresses)


# ============================================================
# БЛОК 5. ДВА IP В ОДНОЙ СЕТИ
# ============================================================
# Условие:
# Проверить, принадлежат ли два IP одной сети при заданной маске.

ip1 = ip_network('192.168.10.25/24', strict=False)
ip2 = ip_network('192.168.10.200/24', strict=False)

print(ip1.network_address == ip2.network_address)


# ============================================================
# БЛОК 6. ПЕРЕБОР МАСОК
# ============================================================
# Условие:
# Маска неизвестна. Нужно найти подходящие длины префикса.

ip1 = '202.3.20.24'
ip2 = '202.3.27.11'

for mask in range(33):
    net1 = ip_network(f'{ip1}/{mask}', strict=False)
    net2 = ip_network(f'{ip2}/{mask}', strict=False)

    if net1.network_address == net2.network_address:
        print(mask)


# ============================================================
# БЛОК 7. ПЕРЕБОР ВСЕХ АДРЕСОВ СЕТИ
# ============================================================
# Условие:
# Посчитать адреса сети, для которых выполняется условие.
# Например: в двоичной записи ровно 10 единиц.

net = ip_network('192.168.1.0/24')
count = 0

for ip in net:
    if bin(int(ip)).count('1') == 10:
        count += 1

print(count)


# ============================================================
# БЛОК 8. ПОДСЧЁТ НУЛЕЙ В 32-БИТНОЙ ЗАПИСИ IP
# ============================================================
# Условие:
# Нужно посчитать нули в двоичной записи IP.
# IPv4 всегда содержит 32 бита, поэтому:
# число нулей = 32 - число единиц.

net = ip_network('192.168.1.0/24')
count = 0

for ip in net:
    zeros = 32 - bin(int(ip)).count('1')

    if zeros == 20:
        count += 1

print(count)


# ============================================================
# БЛОК 9. НЕИЗВЕСТНЫЙ ОКТЕТ IP
# ============================================================
# Условие:
# Один октет неизвестен. Перебираем значения от 0 до 255
# и проверяем условие через адрес сети.

for x in range(256):
    net = ip_network(f'192.168.{x}.86/255.255.252.0', strict=False)

    if str(net.network_address) == '192.168.156.0':
        print(x)


# ============================================================
# БЛОК 10. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# 1. Создаём сеть через ip_network(..., strict=False).
# 2. Берём нужное свойство или перебираем адреса.

net = ip_network('192.168.159.86/22', strict=False)

print(net.network_address)
print(net.netmask)
print(net.prefixlen)
print(net.num_addresses)
print(net.broadcast_address)


