# ============================================================
# БЛОК 1. ЧТЕНИЕ СТРОКИ ИЗ ФАЙЛА
# ============================================================
with open('24.txt') as f:
    s = f.read().strip()


# ============================================================
# БЛОК 2. МАКСИМАЛЬНАЯ ЦЕПОЧКА БЕЗ ЗАПРЕЩЁННОГО СИМВОЛА
# ============================================================
# Например, без символа X.

print(max(map(len, s.split('X'))))


# ============================================================
# БЛОК 3. НЕСКОЛЬКО ЗАПРЕЩЁННЫХ СИМВОЛОВ
# ============================================================
text = s

for c in 'XYZ':
    text = text.replace(c, ' ')

print(max(map(len, text.split())))


# ============================================================
# БЛОК 4. ЗАПРЕЩЁННАЯ ПАРА
# ============================================================
# Например, внутри цепочки не должно быть AA.
# Одна буква A при этом допустима, поэтому split('AA') не подходит:
# он удалит обе буквы и может потерять часть правильного фрагмента.

best = 0
cur = 0

for i in range(len(s)):
    if i > 0 and s[i] == 'A' and s[i - 1] == 'A':
        cur = 1
    else:
        cur += 1

    best = max(best, cur)

print(best)


# ============================================================
# БЛОК 5. НЕ БОЛЕЕ K СИМВОЛОВ — СКОЛЬЗЯЩЕЕ ОКНО
# ============================================================
K = 10
left = 0
cnt = 0
best = 0

for right in range(len(s)):
    if s[right] == 'A':
        cnt += 1

    while cnt > K:
        if s[left] == 'A':
            cnt -= 1
        left += 1

    best = max(best, right - left + 1)

print(best)


# ============================================================
# БЛОК 6. РОВНО K СИМВОЛОВ
# ============================================================
K = 10
left = 0
cnt = 0
best = 0

for right in range(len(s)):
    if s[right] == 'A':
        cnt += 1

    while cnt > K:
        if s[left] == 'A':
            cnt -= 1
        left += 1

    if cnt == K:
        best = max(best, right - left + 1)

print(best)


# ============================================================
# БЛОК 7. ЧЕРЕДОВАНИЕ ТИПОВ СИМВОЛОВ
# ============================================================
def same_type(a, b):
    return a.isalpha() == b.isalpha()


best = 0 if not s else 1
cur = best

for i in range(1, len(s)):
    if not same_type(s[i - 1], s[i]):
        cur += 1
    else:
        cur = 1

    best = max(best, cur)

print(best)


# ============================================================
# БЛОК 8. ВЫДЕЛЕНИЕ ЧИСЕЛ ИЗ СТРОКИ
# ============================================================
# Пример: ищем последовательности символов,
# которые могут быть шестнадцатеричными числами.

text = s
allowed = '0123456789ABCDEF'

for c in set(text):
    if c not in allowed:
        text = text.replace(c, ' ')

numbers = text.split()

print(numbers)


