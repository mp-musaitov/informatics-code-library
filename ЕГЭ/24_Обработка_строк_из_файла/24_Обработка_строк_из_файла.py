print(value)


# ============================================================
# БЛОК 10. РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ ДЛЯ АРИФМЕТИЧЕСКИХ ВЫРАЖЕНИЙ
# ============================================================
# Это альтернатива, а не универсальный шаблон.
# Пример структуры:
# число (операция число)*

import re

pattern = r'(?:0|[1-9][0-9]*)(?:[-*](?:0|[1-9][0-9]*))*'

parts = re.findall(pattern, s)

if parts:
    print(max(map(len, parts)))


