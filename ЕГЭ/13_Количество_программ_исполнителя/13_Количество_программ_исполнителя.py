# ============================================================
# Основная идея:
# каждое число — состояние,
# каждая команда — переход,
# нужно посчитать количество путей от старта к финишу.


# ============================================================
# БЛОК 1. КЛАССИЧЕСКИЙ ШАБЛОН: +1 И *2
# ============================================================
# Условие:
# Исполнитель может прибавить 1 или умножить число на 2.
# Нужно посчитать количество программ из start в finish.


def f(x, finish):
    if x > finish:
        return 0

    if x == finish:
        return 1

    return f(x + 1, finish) + f(x * 2, finish)


print(f(2, 20))


# ============================================================
# БЛОК 2. КОМАНДА С УСЛОВИЕМ
# ============================================================
# Условие:
# Команда B разрешена только при выполнении условия.
# Если условие ложно, остаётся только команда A.


def f(x, finish):
    if x > finish:
        return 0

    if x == finish:
        return 1

    result = f(x + 1, finish)

    if x % 2 == 0:
        result += f(x * 2, finish)

    return result


print(f(2, 20))


# ============================================================
