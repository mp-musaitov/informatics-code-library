# ============================================================
# БЛОК 4. ДЕМОВЕРСИЯ ЕГЭ-2027
# ============================================================
# Условие:
# Старт: 100
# Финиш: 141
# A. Прибавь 1
# B. Поменяй местами две младшие цифры,
#    если цифра десятков меньше цифры единиц.


def change(x):
    return x // 100 * 100 + (x % 10) * 10 + (x // 10) % 10


def f(x, finish):
    if x > finish:
        return 0

    if x == finish:
        return 1

    result = f(x + 1, finish)

    if (x // 10) % 10 < x % 10:
        result += f(change(x), finish)

    return result


print(f(100, 141))


# ============================================================
# БЛОК 5. ТО ЖЕ С МЕМОИЗАЦИЕЙ
# ============================================================
# Условие:
# Если состояний много, сохраняем уже найденные результаты.

from functools import lru_cache


def change(x):
    return x // 100 * 100 + (x % 10) * 10 + (x // 10) % 10


@lru_cache(None)
def f(x):
    if x > 141:
        return 0

    if x == 141:
        return 1

    result = f(x + 1)

    if (x // 10) % 10 < x % 10:
        result += f(change(x))

    return result


print(f(100))


# ============================================================
# БЛОК 6. ОБЯЗАТЕЛЬНО ПРОЙТИ ЧЕРЕЗ ЧИСЛО
# ============================================================
# Условие:
# Нужно пройти через число k.
# Если переходы не создают циклов, считаем:
# start -> k и k -> finish,
# затем перемножаем результаты.


def f(x, finish):
    if x > finish:
        return 0

    if x == finish:
        return 1

    return f(x + 1, finish) + f(x * 2, finish)


start = 2
k = 10
finish = 20

print(f(start, k) * f(k, finish))


# ============================================================
# БЛОК 7. ЗАПРЕЩЁННОЕ ЧИСЛО
# ============================================================
# Условие:
# Через число forbidden проходить нельзя.


def f(x, finish, forbidden):
    if x == forbidden:
        return 0

    if x > finish:
        return 0

    if x == finish:
        return 1

    return f(x + 1, finish, forbidden) + f(x * 2, finish, forbidden)


print(f(2, 20, 10))


# ============================================================
# БЛОК 8. ДИНАМИЧЕСКОЕ ПРОГРАММИРОВАНИЕ
# ============================================================
# Условие:
# Все команды увеличивают число.
# Можно считать количество путей снизу вверх.

start = 2
finish = 20

dp = [0] * (finish + 1)
dp[start] = 1

for x in range(start, finish + 1):
    if x + 1 <= finish:
        dp[x + 1] += dp[x]

    if x * 2 <= finish:
        dp[x * 2] += dp[x]

print(dp[finish])


# ============================================================
# БЛОК 9. КОРОТКИЙ ЭКЗАМЕНАЦИОННЫЙ ШАБЛОН
# ============================================================
# 1. Цель -> return 1
# 2. Тупик -> return 0
# 3. Складываем все разрешённые переходы.


def f(x, finish):
    if x > finish:
        return 0

    if x == finish:
        return 1

    result = f(x + 1, finish)

    if x % 2 == 0:
        result += f(x * 2, finish)

    return result


print(f(2, 20))


